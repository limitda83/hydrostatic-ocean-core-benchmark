#!/usr/bin/env python3
#########################################################################
#  Module: make_sp_cuda                                                 #
#  Description: Generates the fp32 variant of the CUDA v0.5/v0.6 core   #
#               from the fp64 source (axis G). Two mechanical rules,     #
#               applied outside strings, comments and preprocessor       #
#               lines: `double` becomes the alias `real_t`, and every    #
#               floating literal is wrapped in R(...) so it takes the    #
#               working precision instead of promoting the expression    #
#               to double. Host-side file I/O keeps `double` (the        #
#               bundle on disk is fp64 in both builds, R9) via an        #
#               explicit opt-out marker.                                #
#               Verification: built with -DCFD_REAL=double the generated #
#               file must reproduce the original binary bit for bit.     #
#  Pipeline: cfd_exp3d5_cuda.cu -> make_sp_cuda -> cfd_exp3d5_cuda_sp.cu #
#########################################################################

from __future__ import annotations

import argparse
import re
from pathlib import Path

# Lines carrying this marker keep `double`: host buffers that mirror the file.
KEEP = "fp64-io"           # a line carrying this marker keeps `double`
HEADER = """/* GENERATED by tools/make_sp_cuda.py from cfd_exp3d5_cuda.cu - do not edit.
 * `real_t` is the working precision (-DCFD_REAL=float | double); every floating
 * literal is wrapped in R() so that it carries that precision. Host-side file
 * I/O stays fp64: the bundle on disk is fp64 in both builds (RULES.md R9).
 */
#ifndef CFD_REAL
#define CFD_REAL float
#endif
using real_t = CFD_REAL;
#define R(x) (static_cast<real_t>(x))
#define PRECISION_NAME (sizeof(real_t) == 4 ? "fp32" : "fp64")
"""

FLOAT_LIT = re.compile(r"""
    (?<![\w.])                       # not inside an identifier or a member access
    (?: \d+\.\d*(?:[eE][-+]?\d+)?    # 1.  1.5  1.5e-3
      | \.\d+(?:[eE][-+]?\d+)?       # .5
      | \d+[eE][-+]?\d+ )            # 1e-12
    (?![\w.])                        # not followed by more of a number/identifier
""", re.X)


def split_code(line: str) -> list[tuple[str, bool]]:
    """Split a line into (text, is_code) pieces, so that string literals,
    character literals and // comments are never rewritten."""
    out: list[tuple[str, bool]] = []
    i, n, start = 0, len(line), 0
    while i < n:
        c = line[i]
        if c == '"' or c == "'":
            out.append((line[start:i], True))
            q, j = c, i + 1
            while j < n and line[j] != q:
                j += 2 if line[j] == "\\" else 1
            out.append((line[i:j + 1], False))
            i = start = j + 1
            continue
        if c == "/" and i + 1 < n and line[i + 1] in "/*":
            out.append((line[start:i], True))
            out.append((line[i:], False))
            return out
        i += 1
    out.append((line[start:], True))
    return out


def convert(src: str) -> str:
    lines = src.splitlines()
    out: list[str] = []
    inserted = False
    in_block_comment = False
    for line in lines:
        stripped = line.lstrip()
        # keep the module header comment, then inject our preamble after it
        if not inserted and stripped.startswith("#include"):
            out.append(HEADER)
            inserted = True
        if in_block_comment:
            out.append(line)
            if "*/" in line:
                in_block_comment = False
            continue
        if stripped.startswith("/*") and "*/" not in line:
            in_block_comment = True
            out.append(line)
            continue
        if stripped.startswith("#") or KEEP in line:
            out.append(line)                      # preprocessor lines, fp64 I/O
            continue
        pieces = []
        for text, is_code in split_code(line):
            if is_code:
                text = re.sub(r"\bdouble\b", "real_t", text)
                text = FLOAT_LIT.sub(lambda m: f"R({m.group(0)})", text)
            pieces.append(text)
        out.append("".join(pieces))
    body = "\n".join(out) + "\n"
    # the JSON writer and the file I/O use double deliberately; restore the
    # few places where a real_t would break a printf/fread contract.
    # the state writer stages fp64: its element type follows the working precision
    body = body.replace("using real_t_or_double = real_t;", "using real_t_or_double = real_t;")
    return body


def main() -> int:
    ap = argparse.ArgumentParser(description="generate the fp32 CUDA variant")
    ap.add_argument("src", type=Path, nargs="?",
                    default=Path("libs/cuda/src/cfd_exp3d5_cuda.cu"))
    ap.add_argument("--out", type=Path, default=Path("libs/cuda/src/cfd_exp3d5_cuda_sp.cu"))
    args = ap.parse_args()
    text = convert(args.src.read_text())
    args.out.write_text(text)
    n_real = text.count("real_t")
    n_lit = text.count("R(")
    print(f"{args.out}: real_t {n_real} occurrences, {n_lit} wrapped literals")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
