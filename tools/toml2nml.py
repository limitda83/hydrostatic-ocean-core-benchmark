#!/usr/bin/env python3
#########################################################################
#  Module: toml2nml                                                     #
#  Description: Generate the Fortran namelist for the compiled backends #
#               from config/*.toml, so that every backend is driven by  #
#               one configuration tree (RULES.md R3). dt and n_steps   #
#               are resolved here, not in Fortran, so both backends     #
#               integrate exactly the same discrete problem.            #
#  Pipeline: config/*.toml -> toml2nml -> <run>.nml -> compiled backend #
#########################################################################

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

from libs.core.cases import build_case
from libs.core.cases3d import build_case3d
from libs.core.driver3d import physics3d_from_config
from libs.core.grid import build_grid
from libs.core.schemes import (explicit_dt_max, physics_from_config,
                               scheme_params_from_config)
from libs.utils.config import Config, load_config


def _fd(value: float) -> str:
    """Format a float as a valid Fortran double literal, full fp64 precision.

    repr() alone is not enough: repr(1e-12) is "1e-12", and appending "d0"
    yields "1e-12d0", which has two exponent markers and is rejected by the
    namelist reader.
    """
    return f"{float(value):.17e}".replace("e", "d")


def resolve_run(config: Config, nx: int, cfl: float, case_name: str,
                n_steps_override: int | None = None,
                nz: int | None = None) -> dict[str, Any]:
    """Resolve grid, scheme, case and the exact (dt, n_steps) pair.

    ``nz`` selects the 3D model; the same function serves both so the two
    backends can never disagree about dt or the step count.
    """
    if nz is not None:
        grid = build_grid(config, nx=nx, ny=nx, nz=nz)
        physics = physics3d_from_config(config)
        params = scheme_params_from_config(config)
        _, t_final_case = build_case3d(case_name, grid, physics, config)
        spec = None
    else:
        grid = build_grid(config, nx=nx, ny=nx)
        physics = physics_from_config(config)
        params = scheme_params_from_config(config)
        case, spec = build_case(case_name, grid, physics, config)
        t_final_case = spec.t_final

    dt_max = explicit_dt_max(grid, physics)
    pinned = float(config.get("time.dt", 0.0))
    dt_req = pinned if pinned > 0.0 else cfl * dt_max
    if n_steps_override is not None:
        n_steps, dt = n_steps_override, dt_req
        t_final = dt * n_steps
    else:
        n_steps = max(1, int(round(t_final_case / dt_req)))
        dt = t_final_case / n_steps
        t_final = t_final_case
    return {"grid": grid, "physics": physics, "params": params, "spec": spec,
            "dt": dt, "dt_max": dt_max, "n_steps": n_steps, "t_final": t_final}


def write_namelist(path: Path, config: Config, resolved: dict[str, Any],
                   case_name: str, out_prefix: str, n_repeat: int,
                   n_warmup: int, omp_min_points: int = 65536,
                   tridiag_kernel: str = "plane",
                   pcg_sync: str = "device",
                   pcg_check_every: int = 5) -> Path:
    grid, physics, params = resolved["grid"], resolved["physics"], resolved["params"]
    case_cfg = config.section(f"case.{case_name}")
    case_cfg.setdefault("eta0", 1.0)
    n_modes = int(case_cfg.get("n_modes", 0))
    slope = float(case_cfg.get("slope", 0.0))
    path.parent.mkdir(parents=True, exist_ok=True)
    text = f"""! Generated by tools/toml2nml.py from {config.source_dir}/*.toml
! Do not edit by hand - edit the TOML files instead (RULES.md R3).
&grid_nml
  nx = {grid.nx}
  ny = {grid.ny}
  nz = {grid.nz}
  lx = {_fd(grid.Lx)}
  ly = {_fd(grid.Ly)}
/
&physics_nml
  g  = {_fd(physics.g)}
  f0 = {_fd(physics.f)}
  h0 = {_fd(physics.H)}
  n2 = {_fd(config.get("physics3d.N2", 0.0))}
  nu = {_fd(config.get("physics3d.nu", 0.0))}
  kappa = {_fd(config.get("physics3d.kappa", 0.0))}
  rho0 = {_fd(config.get("physics.rho0", 1025.0))}
  tau_x = {_fd(config.get("physics3d.tau_x", 0.0))}
  tau_y = {_fd(config.get("physics3d.tau_y", 0.0))}
  bottom_drag = {_fd(config.get("physics3d.bottom_drag", 0.0))}
/
&scheme_nml
  scheme_name = '{params.name}'
  theta       = {_fd(params.theta)}
  theta_cor   = {_fd(params.theta_cor)}
  theta_v     = {_fd(params.theta_v)}
  n_picard    = {params.n_picard}
  n_split     = {params.n_split}
  solver_kind = '{params.solver}'
  rtol        = {_fd(params.rtol)}
  max_iter    = {params.max_iter}
/
&case_nml
  case_name = '{case_name}'
  mode_x    = {int(case_cfg.get("mode_x", 0))}
  mode_y    = {int(case_cfg.get("mode_y", 0))}
  n_modes   = {n_modes}
  slope     = {_fd(slope)}
  mode_z    = {int(case_cfg.get("mode_z", 1))}
  u0        = {_fd(case_cfg.get("u0", 1.0))}
  eta0      = {_fd(case_cfg["eta0"])}
/
&run_nml
  dt         = {_fd(resolved["dt"])}
  t_final    = {_fd(resolved["t_final"])}
  n_steps    = {resolved["n_steps"]}
  n_repeat   = {n_repeat}
  n_warmup   = {n_warmup}
  omp_min_points = {omp_min_points}
  tridiag_kernel = '{tridiag_kernel}'
  pcg_sync = '{pcg_sync}'
  pcg_check_every = {pcg_check_every}
  out_prefix = '{out_prefix}'
/
"""
    path.write_text(text, encoding="utf-8")
    return path


def write_v05_bundle(prefix: str, config: Config, nx: int, nz: int,
                     case_name: str, cfl: float, n_steps_override: int | None,
                     n_repeat: int, n_warmup: int, omp_min_points: int = 65536,
                     tridiag_kernel: str = "plane") -> dict[str, Any]:
    """Namelist + domain and initial-state binaries for the v0.5 backend.

    The domain, the initial state and the exact (dt, n_steps) pair all come
    from the NumPy reference, so the compiled backend integrates the same
    discrete problem bit for bit (R2). Binaries are float64 in Fortran
    (nx,ny[,nz]) order, which is NumPy [nz,ny,nx] C order.
    """
    import numpy as np
    from libs.core.cases3d_v05 import build_case3d_v05
    from libs.core.driver3d_v05 import (barotropic_dt_max, build_domain3d,
                                        physics_v05_from_config)
    domain = build_domain3d(config, nx, nz)
    physics = physics_v05_from_config(config)
    params = scheme_params_from_config(config)
    case = build_case3d_v05(case_name, domain, physics, config)
    dt_max = barotropic_dt_max(domain, physics.g)
    dt_req = cfl * dt_max
    if n_steps_override is not None:
        n_steps, dt = n_steps_override, dt_req
    else:
        n_steps = max(1, int(round(case.t_final / dt_req)))
        dt = case.t_final / n_steps
    t_final = dt * n_steps

    out = Path(prefix)
    out.parent.mkdir(parents=True, exist_ok=True)
    domain_file = f"{prefix}_domain.bin"
    init_file = f"{prefix}_init.bin"
    with open(domain_file, "wb") as fh:
        fh.write(domain.H.astype(np.float64).tobytes())
        fh.write(domain.mask.astype(np.float64).tobytes())
    s0 = case.initial()
    with open(init_file, "wb") as fh:
        for arr in (s0.eta, s0.u, s0.v, s0.b):
            fh.write(np.ascontiguousarray(arr, dtype=np.float64).tobytes())
        if physics.tracers == "TS":
            fh.write(np.ascontiguousarray(s0.T, dtype=np.float64).tobytes())
            fh.write(np.ascontiguousarray(s0.S, dtype=np.float64).tobytes())

    g = domain.grid
    v5 = physics
    text = f"""! Generated by tools/toml2nml.py --v05 from {config.source_dir}/*.toml
! Do not edit by hand - edit the TOML files instead (RULES.md R3).
&grid_nml
  nx = {g.nx}
  ny = {g.ny}
  nz = {g.nz}
  lx = {_fd(g.Lx)}
  ly = {_fd(g.Ly)}
/
&physics_nml
  g  = {_fd(physics.g)}
  f0 = {_fd(physics.f)}
  h0 = {_fd(physics.H)}
  n2 = {_fd(physics.N2)}
  nu = {_fd(physics.nu)}
  kappa = {_fd(physics.kappa)}
  rho0 = {_fd(physics.rho0)}
  tau_x = {_fd(physics.tau_x)}
  tau_y = {_fd(physics.tau_y)}
  bottom_drag = {_fd(physics.bottom_drag)}
/
&scheme_nml
  scheme_name = '{params.name}'
  theta       = {_fd(params.theta)}
  theta_cor   = {_fd(params.theta_cor)}
  theta_v     = {_fd(params.theta_v)}
  n_picard    = {params.n_picard}
  n_split     = {params.n_split}
  solver_kind = '{params.solver}'
  rtol        = {_fd(params.rtol)}
  max_iter    = {params.max_iter}
/
&case_nml
  case_name = '{case_name}'
/
&run_nml
  dt         = {_fd(dt)}
  t_final    = {_fd(t_final)}
  n_steps    = {n_steps}
  n_repeat   = {n_repeat}
  n_warmup   = {n_warmup}
  omp_min_points = {omp_min_points}
  tridiag_kernel = '{tridiag_kernel}'
  pcg_sync = 'device'
  pcg_check_every = 1
  out_prefix = '{prefix}'
/
&v05_nml
  vcoord = '{domain.vcoord}'
  bc_x = '{domain.bc_x}'
  bc_y = '{domain.bc_y}'
  face_rule = '{domain.face_rule}'
  min_partial = {_fd(domain.min_partial)}
  eos = '{v5.eos}'
  pgf = '{v5.pgf}'
  pgf_correction = {'.true.' if v5.pgf_correction else '.false.'}
  advection = '{params.advection}'
  tracers = '{physics.tracers}'
  alpha_t = {_fd(physics.alpha_T)}
  beta_s = {_fd(physics.beta_S)}
  t0 = {_fd(physics.T0)}
  s0 = {_fd(physics.S0)}
  cp = {_fd(physics.cp)}
  a_h = {_fd(physics.A_h)}
  k_h = {_fd(physics.K_h)}
  q_heat = {_fd(physics.q_heat)}
  q_salt = {_fd(physics.q_salt)}
  closure = '{v5.closure}'
  c_k = {_fd(v5.c_k)}
  c_eps = {_fd(v5.c_eps)}
  pr_t = {_fd(v5.pr_t)}
  z_0 = {_fd(v5.z_0)}
  e_min = {_fd(v5.e_min)}
  l_min = {_fd(v5.l_min)}
  e_bb = {_fd(v5.e_bb)}
  n2_min = {_fd(v5.n2_min)}
  mxl = '{v5.mxl}'
  domain_file = '{domain_file}'
  init_file = '{init_file}'
/
"""
    nml = Path(f"{prefix}.nml")
    nml.write_text(text, encoding="utf-8")
    return {"nml": nml, "dt": dt, "n_steps": n_steps, "t_final": t_final,
            "dt_max": dt_max, "domain": domain, "physics": physics,
            "params": params, "case": case, "state0": s0}


def main() -> int:
    parser = argparse.ArgumentParser(description="TOML -> Fortran namelist")
    parser.add_argument("--v05", action="store_true",
                        help="spec v0.5 bundle: namelist + domain/init binaries")
    parser.add_argument("--config", default="config", type=Path)
    parser.add_argument("--set", action="append", default=[], metavar="KEY=VALUE")
    parser.add_argument("--case", default=None)
    parser.add_argument("--nx", type=int, default=None)
    parser.add_argument("--cfl", type=float, default=None)
    parser.add_argument("--steps", type=int, default=None,
                        help="pin the step count instead of integrating to t_final")
    parser.add_argument("--nz", type=int, default=None,
                        help="vertical layers; selects the 3D model")
    parser.add_argument("--out", type=Path, default=Path("output/fortran/run.nml"))
    parser.add_argument("--prefix", default="output/fortran/run")
    parser.add_argument("--n-repeat", type=int, default=5)
    parser.add_argument("--n-warmup", type=int, default=1)
    args = parser.parse_args()

    from main import _apply_overrides           # reuse the driver's parser
    config = _apply_overrides(load_config(args.config), args.set)
    case_name = args.case or config.get("case.name")
    nx = args.nx or int(config.get("grid.nx"))
    cfl = args.cfl if args.cfl is not None else float(config.get("time.cfl_factor"))

    if args.v05:
        # The OpenMP threshold is machine dependent (config/backends.toml); the
        # bundle carries the configured value so --set can switch it off.
        omp_min = int(config.section("backends.fortran_cpu").get("omp_min_points", 65536))
        r = write_v05_bundle(args.prefix, config, nx, args.nz or int(config.get("grid.nz")),
                             case_name, cfl, args.steps, args.n_repeat, args.n_warmup,
                             omp_min_points=omp_min)
        print(f"{r['nml']}  (dt={r['dt']:.6f}s, n_steps={r['n_steps']}, "
              f"cfl={r['dt'] / r['dt_max']:.3f}, v0.5 bundle)")
        return 0
    resolved = resolve_run(config, nx, cfl, case_name, args.steps, args.nz)
    path = write_namelist(args.out, config, resolved, case_name, args.prefix,
                          args.n_repeat, args.n_warmup)
    print(f"{path}  (dt={resolved['dt']:.6f}s, n_steps={resolved['n_steps']}, "
          f"cfl={resolved['dt'] / resolved['dt_max']:.3f})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
