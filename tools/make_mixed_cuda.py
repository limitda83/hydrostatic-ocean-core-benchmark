#!/usr/bin/env python3
#########################################################################
#  Module: make_mixed_cuda                                              #
#  Description: Generates the MIXED-precision CUDA core from the fp64   #
#               source: fp64 everywhere except inside the body of the   #
#               TKE closure kernel `k_closure`, which computes in        #
#               `closure_t` (-DCLOSURE_T=float). The kernel's signature #
#               and every global array stay double, so inputs are read  #
#               as double and narrowed on load; outputs are widened on  #
#               store. This is the "fp64 core + low-precision module"   #
#               structure docs/37 S2-3 argues a learned closure would    #
#               take. Reuses make_sp_cuda's literal/typename rewriting, #
#               scoped to that one function body.                       #
#               Verification: -DCLOSURE_T=double must reproduce the      #
#               original binary's state file bit for bit.               #
#  Pipeline: cfd_exp3d5_cuda.cu -> make_mixed_cuda -> _mixed.cu          #
#########################################################################

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_sp_cuda import FLOAT_LIT, split_code  # noqa: E402

HEADER = """/* GENERATED by tools/make_mixed_cuda.py from cfd_exp3d5_cuda.cu - do not edit.
 * Only the body of k_closure is retyped: `closure_t` (-DCLOSURE_T=float | double)
 * and RC() on its floating literals. Everything else, including the kernel's
 * signature and every device array, is the fp64 original.
 */
#ifndef CLOSURE_T
#define CLOSURE_T float
#endif
using closure_t = CLOSURE_T;
#define RC(x) (static_cast<closure_t>(x))
#define CLOSURE_PRECISION_NAME (sizeof(closure_t) == 4 ? "fp32" : "fp64")
"""


# Everything the closure body reads from the fp64 world. Each is narrowed to
# closure_t AT THE LOAD, so the arithmetic that follows runs in the closure's
# precision instead of silently promoting back to double (which is also what
# made nvcc pick the host fmax(float,double) template and refuse to compile).
SCALARS = ("dt", "nu_b", "kap_b", "ustar2", "c_k", "c_eps", "pr_t", "z_0", "e_min",
           "l_min", "e_bb", "n2_min")
ARRAYS = ("u", "v", "b", "d.dz3", "d.mask3", "d.tke", "d.nu3", "d.kap3")


def wrap_balanced(text: str, head: str, open_ch: str, close_ch: str) -> str:
    """Wrap every `head<open>...<close>` (balanced) occurrence in RC( ... )."""
    out, i = [], 0
    pat = re.compile(r"(?<![\w.])" + re.escape(head) + re.escape(open_ch))
    while True:
        m = pat.search(text, i)
        if not m:
            out.append(text[i:]); break
        j, depth = m.end(), 1
        while j < len(text) and depth:
            depth += (text[j] == open_ch) - (text[j] == close_ch); j += 1
        out.append(text[i:m.start()]); out.append(f"RC({text[m.start():j]})"); i = j
    return "".join(out)


def retype(line: str) -> str:
    out = []
    for text, is_code in split_code(line):
        if is_code:
            text = re.sub(r"\bdouble\b", "closure_t", text)
            text = FLOAT_LIT.sub(lambda m: f"RC({m.group(0)})", text)
            for a in ARRAYS:                      # loads: RC(u[...]), RC(d.tke[...])
                text = wrap_balanced(text, a, "[", "]")
            text = wrap_balanced(text, "safe_inv", "(", ")")   # returns double
            for name in SCALARS:                  # kernel parameters are double
                text = re.sub(r"(?<![\w.])" + name + r"(?![\w(])", f"RC({name})", text)
        out.append(text)
    return "".join(out)


def convert(src: str) -> str:
    lines = src.splitlines()
    # locate k_closure: signature (may span lines up to the first '{'), then
    # the body up to the matching closing brace at column 0.
    start = next(i for i, l in enumerate(lines) if l.startswith("__global__ void k_closure("))
    sig_end = next(i for i in range(start, len(lines)) if lines[i].rstrip().endswith("{"))
    end = next(i for i in range(sig_end + 1, len(lines)) if lines[i].startswith("}"))
    body = []
    for l in lines[sig_end + 1:end]:
        r = retype(l)
        # a wrapped load on the LEFT of an assignment is a store: unwrap it
        r = re.sub(r"RC\((d\.(?:tke|nu3|kap3)\[[^\n=]*?\])\)(\s*=[^=])", r"\1\2", r)
        body.append(r)
    out = lines[:sig_end + 1] + body + lines[end:]
    # preamble after the module header comment, before the first #include
    inc = next(i for i, l in enumerate(out) if l.lstrip().startswith("#include"))
    out = out[:inc] + HEADER.splitlines() + out[inc:]
    n_double = sum(len(re.findall(r"\bclosure_t\b", l)) for l in body)
    n_lit = sum(len(re.findall(r"RC\(", l)) for l in body)
    print(f"k_closure body: lines {sig_end + 2}-{end} of the source, "
          f"{n_double} closure_t, {n_lit} wrapped literals", file=sys.stderr)
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("src", nargs="?", type=Path, default=Path("libs/cuda/src/cfd_exp3d5_cuda.cu"))
    ap.add_argument("--out", type=Path, default=Path("libs/cuda/src/cfd_exp3d5_cuda_mixed.cu"))
    a = ap.parse_args()
    a.out.write_text(convert(a.src.read_text()))
    print(a.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
