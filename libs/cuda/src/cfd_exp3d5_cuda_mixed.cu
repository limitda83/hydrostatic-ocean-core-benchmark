struct Stepper5 {
    RunConfig c; V05Config v5; Domain dom; Dev d; HelmVar solver;
    bool is_theta, is_split, is_ts, do_adv, is_up3, is_tvd, is_tke;
    int n_split = 0; double dz_nom;
    long tridiag = 0, substeps = 0, rebuilds = 0;
    int eos_kind = 0;
    dim3 b3 = dim3(32, 8, 1), g3, b2 = dim3(32, 8), g2;

    Stepper5(const RunConfig& c_, const V05Config& v_, Domain&& dom_) : c(c_), v5(v_), dom(std::move(dom_)) {
        d.nx = c.nx; d.ny = c.ny; d.nz = c.nz; d.n2 = c.nx * c.ny; d.n3 = d.n2 * c.nz; d.n3i = d.n2 * (c.nz + 1);
        d.dx = c.lx / c.nx; d.dy = c.ly / c.ny;
        g3 = dim3((c.nx + 31) / 32, (c.ny + 7) / 8, c.nz); g2 = dim3((c.nx + 31) / 32, (c.ny + 7) / 8);
        is_theta = c.scheme_name == "theta"; is_split = c.scheme_name == "split_explicit";
        is_ts = v5.tracers == "TS"; do_adv = v5.advection != "none";
        is_up3 = v5.advection == "up3" || v5.advection == "up3_tvd"; is_tvd = v5.advection == "up3_tvd";
        is_tke = v5.closure == "tke";
        eos_kind = v5.eos == "linear" ? 0 : (v5.eos == "seos" ? 1 : 2);
        dz_nom = c.h0 / c.nz;
        /* domain to device */
        d.mask = dev_from(dom.mask); d.masku = dev_from(dom.masku); d.maskv = dev_from(dom.maskv);
        d.dz3 = dev_from(dom.dz3); d.dz3u = dev_from(dom.dz3u); d.dz3v = dev_from(dom.dz3v);
        d.mask3 = dev_from(dom.mask3); d.mask3u = dev_from(dom.mask3u); d.mask3v = dev_from(dom.mask3v);
        d.inv_dz3 = dev_from(dom.inv_dz3); d.zc = dev_from(dom.zc); d.inv_hcu = dev_from(dom.inv_hcu); d.inv_hcv = dev_from(dom.inv_hcv);
        std::vector<double> tu(d.n2), tv(d.n2), ft(d.n2, v5.q_heat / (c.rho0 * v5.cp)), fs(d.n2, v5.q_salt), z2(d.n2, 0.0);
        for (int i = 0; i < d.n2; ++i) { tu[i] = c.tau_x / c.rho0 * dom.mask3u[i]; tv[i] = c.tau_y / c.rho0 * dom.mask3v[i]; }
        d.tau_u = dev_from(tu); d.tau_v = dev_from(tv); d.flux_t = dev_from(ft); d.flux_s = dev_from(fs); d.zero2 = dev_from(z2);
        for (double** p : {&d.msub, &d.mdiag, &d.msup, &d.bsub, &d.bdiag, &d.bsup, &d.cstar, &d.q, &d.phi, &d.pgx, &d.pgy,
                           &d.avpu, &d.avpv, &d.ucor, &d.vcor, &d.dzu, &d.dzv, &d.exu, &d.exv, &d.gu, &d.gv, &d.ghu, &d.ghv,
                           &d.uit, &d.vit, &d.tend, &d.trhs, &d.tnew, &d.dzb, &d.w3a, &d.w3b, &d.w3c, &d.w3d})
            *p = dev_zero(d.n3);
        d.wf = dev_zero(d.n3i); d.wold = dev_zero(d.n3i);
        std::vector<double> nu_i(d.n3i, c.nu), kap_i(d.n3i, c.kappa), tke0(d.n3i, v5.e_min);
        d.nu3 = dev_from(nu_i); d.kap3 = dev_from(kap_i); d.tke = dev_from(tke0);
        for (double** p : {&d.uint, &d.vint, &d.divold, &d.divg, &d.rhs2, &d.etanew, &d.gx2, &d.gy2, &d.bu, &d.bv, &d.bui, &d.bvi,
                           &d.bavu, &d.bavv, &d.bucor, &d.bvcor, &d.bfx, &d.bfy, &d.corx, &d.cory, &d.umean, &d.vmean, &d.ku, &d.kv})
            *p = dev_zero(d.n2);
        build_coefficients(true);
        if (is_split) {
            double cc = std::sqrt(c.g * dom.hmax), dt_baro = 1.0 / (cc * std::sqrt(1.0 / (d.dx * d.dx) + 1.0 / (d.dy * d.dy)));
            n_split = c.n_split > 0 ? c.n_split : std::max(1, (int)std::ceil(1.2 * c.dt / dt_baro));
        }
    }

    /* Tridiagonal solve followed by the cell mask, as the Fortran does after
     * every call except the q = A^{-1} 1 solve of the constructor. */
    /* Tridiagonal coefficients, q = A^-1 1, Ku/Kv and the Helmholtz operator for
     * the current nu3/kap3 (mod_model3d_v05::build_coefficients). */
    void build_coefficients(bool first) {
        k_diff_coeffs<<<g3, b3>>>(d, c.theta_v, c.dt, d.nu3, c.bottom_drag, d.dz3, d.msub, d.mdiag, d.msup);
        k_diff_coeffs<<<g3, b3>>>(d, c.theta_v, c.dt, d.kap3, 0.0, d.dz3, d.bsub, d.bdiag, d.bsup);
        k3_fill<<<g3, b3>>>(d, d.w3a, 1.0);
        k_thomas<<<g2, b2>>>(d.msub, d.mdiag, d.msup, d.w3a, d.q, d.cstar, d.nx, d.ny, d.nz);
        ++tridiag;
        k2_kukv<<<g2, b2>>>(d, d.q, d.ku, d.kv);
        if (is_theta) {
            if (first) {
                std::vector<double> ku(d.n2), kv(d.n2);
                CUDA_OK(cudaMemcpy(ku.data(), d.ku, d.n2 * sizeof(double), cudaMemcpyDeviceToHost));
                CUDA_OK(cudaMemcpy(kv.data(), d.kv, d.n2 * sizeof(double), cudaMemcpyDeviceToHost));
                solver.init(d.nx, d.ny, d.dx, d.dy, c.g * c.theta * c.theta * c.dt * c.dt, ku, kv, dom.mask,
                            c.solver_kind, c.rtol, c.max_iter);
            } else { solver.update(d.ku, d.kv); ++rebuilds; }
        }
    }
    void closure_step(const double* u, const double* v, const double* b) {
        double ustar2 = std::sqrt(c.tau_x * c.tau_x + c.tau_y * c.tau_y) / c.rho0;
        k_closure<<<g2, b2>>>(d, u, v, b, c.dt, c.nu, c.kappa, ustar2, v5.c_k, v5.c_eps, v5.pr_t, v5.z_0, v5.e_min, v5.l_min, v5.e_bb, v5.n2_min, v5.mxl == "recursive");
        ++tridiag;
        build_coefficients(false);
    }
    void thomas(const double* sub, const double* diag, const double* sup, const double* rhs, double* x) {
        k_thomas<<<g2, b2>>>(sub, diag, sup, rhs, x, d.cstar, d.nx, d.ny, d.nz); ++tridiag;
        k3_mask<<<g3, b3>>>(d, x);
    }
    void advance_tracer(const double* cc, const double* u, const double* v, const double* wf, const double* sflux, const double* source, double* cnew) {
        k3_copy<<<g3, b3>>>(d, source, d.tend);
        if (do_adv) { k_tracer_adv<<<g3, b3>>>(d, cc, u, v, wf, v5.advection == "upwind1", is_up3, is_tvd, d.w3b); k3_axpy<<<g3, b3>>>(d, d.tend, -1.0, d.w3b); }
        if (v5.k_h > 0.0) { k_lap_m<<<g3, b3>>>(d, cc, d.mask3u, d.mask3v, d.mask3, d.w3b); k3_axpy<<<g3, b3>>>(d, d.tend, v5.k_h, d.w3b); }
        k_apply_diff<<<g3, b3>>>(d, cc, d.kap3, d.dz3, sflux, 0.0, d.dzb);
        k_tracer_rhs<<<g3, b3>>>(d, cc, d.tend, d.dzb, sflux, c.dt, c.theta_v, d.trhs);
        thomas(d.bsub, d.bdiag, d.bsup, d.trhs, cnew);
    }
    void advance_tracers(double* b, double* t, double* s, const double* u, const double* v, const double* wf) {
        if (is_ts) {
            k3_fill<<<g3, b3>>>(d, d.w3a, 0.0);
            advance_tracer(t, u, v, wf, d.flux_t, d.w3a, d.tnew); k3_copy<<<g3, b3>>>(d, d.tnew, t);
            advance_tracer(s, u, v, wf, d.flux_s, d.w3a, d.tnew); k3_copy<<<g3, b3>>>(d, d.tnew, s);
            k3_eos<<<g3, b3>>>(d, t, s, eos_kind, c.g, c.rho0, v5.alpha_t, v5.beta_s, v5.t0, v5.s0, b);
        } else {
            k3_wcsrc<<<g3, b3>>>(d, wf, c.n2, d.w3a);
            advance_tracer(b, u, v, wf, d.zero2, d.w3a, d.tnew); k3_copy<<<g3, b3>>>(d, d.tnew, b);
        }
    }

    void step(double* u, double* v, double* b, double* eta, double* t, double* s) {
        /* fb applies the full explicit surface gradient: theta is the theta scheme's (N14) */
        const double dt = c.dt, f = c.f0, th = is_theta ? c.theta : 0.0, tc = c.theta_cor, thv = c.theta_v;
        const double c1 = c.g * dt * (1.0 - th), c2 = c.g * dt * th;
        if (is_tke) closure_step(u, v, b);                       /* S11.2: closure first */
        /* shared predictor */
        k_phi<<<g2, b2>>>(d, b, v5.pgf == "remove", d.phi);
        k_pg<<<g3, b3>>>(d, b, d.phi, v5.pgf_correction, d.pgx, d.pgy);
        k_avg_v_to_u<<<g3, b3>>>(d, v, d.mask3v, d.mask3u, d.avpv);
        k_avg_u_to_v<<<g3, b3>>>(d, u, d.mask3u, d.mask3v, d.avpu);
        k_apply_diff<<<g3, b3>>>(d, u, d.nu3, d.dz3u, d.tau_u, c.bottom_drag, d.dzu);
        k_apply_diff<<<g3, b3>>>(d, v, d.nu3, d.dz3v, d.tau_v, c.bottom_drag, d.dzv);
        k_w_transport<<<g2, b2>>>(d, u, v, d.wold);
        k3_fill<<<g3, b3>>>(d, d.exu, 0.0); k3_fill<<<g3, b3>>>(d, d.exv, 0.0);
        if (is_up3) k_mom_adv_up3<<<g3, b3>>>(d, u, v, d.wold, dz_nom, is_tvd, d.exu, d.exv);
        else if (do_adv) k_mom_adv<<<g3, b3>>>(d, u, v, d.wold, dz_nom, d.exu, d.exv);
        if (v5.a_h > 0.0) {
            k_lap_m<<<g3, b3>>>(d, u, d.mask3u, d.mask3v, d.mask3u, d.w3c); k3_axpy<<<g3, b3>>>(d, d.exu, v5.a_h, d.w3c);
            k_lap_m<<<g3, b3>>>(d, v, d.mask3u, d.mask3v, d.mask3v, d.w3d); k3_axpy<<<g3, b3>>>(d, d.exv, v5.a_h, d.w3d);
        }
        k3_stress<<<g3, b3>>>(d, d.exu, d.exv, dt, thv, d.w3c, d.w3d);
        if (is_split) { step_split(u, v, b, eta, t, s); return; }

        k2_grad<<<g2, b2>>>(d, eta, d.gx2, d.gy2);
        k_depth_transport<<<g2, b2>>>(d, u, d.dz3u, d.uint); k_depth_transport<<<g2, b2>>>(d, v, d.dz3v, d.vint);
        k2_div<<<g2, b2>>>(d, d.uint, d.vint, d.divold);
        k3_copy<<<g3, b3>>>(d, u, d.uit); k3_copy<<<g3, b3>>>(d, v, d.vit);
        for (int m = 0; m < c.n_picard; ++m) {
            k_avg_v_to_u<<<g3, b3>>>(d, d.vit, d.mask3v, d.mask3u, d.vcor);
            k_avg_u_to_v<<<g3, b3>>>(d, d.uit, d.mask3u, d.mask3v, d.ucor);
            k3_predictor<<<g3, b3>>>(d, u, v, dt, f, tc, c1, thv, true, d.avpv, d.avpu, d.vcor, d.ucor, d.pgx, d.pgy, d.gx2, d.gy2, d.dzu, d.dzv, d.w3c, d.w3d, d.gu, d.gv);
            thomas(d.msub, d.mdiag, d.msup, d.gu, d.ghu); thomas(d.msub, d.mdiag, d.msup, d.gv, d.ghv);
            if (is_theta) {
                k_depth_transport<<<g2, b2>>>(d, d.ghu, d.dz3u, d.uint); k_depth_transport<<<g2, b2>>>(d, d.ghv, d.dz3v, d.vint);
                k2_div<<<g2, b2>>>(d, d.uint, d.vint, d.divg);
                k2_rhs_eta<<<g2, b2>>>(d, eta, d.divold, d.divg, dt, th, d.rhs2);
                solver.solve(d.rhs2, d.etanew);
                k2_grad<<<g2, b2>>>(d, d.etanew, d.gx2, d.gy2);
                k3_backsub<<<g3, b3>>>(d, d.ghu, d.ghv, d.q, d.gx2, d.gy2, c2, d.uit, d.vit);
                if (m < c.n_picard - 1) k2_grad<<<g2, b2>>>(d, eta, d.gx2, d.gy2);
            } else { k3_copy<<<g3, b3>>>(d, d.ghu, d.uit); k3_copy<<<g3, b3>>>(d, d.ghv, d.vit); }
        }
        if (!is_theta) {
            k_depth_transport<<<g2, b2>>>(d, d.uit, d.dz3u, d.uint); k_depth_transport<<<g2, b2>>>(d, d.vit, d.dz3v, d.vint);
            k2_div<<<g2, b2>>>(d, d.uint, d.vint, d.divg);
            k2_eta_fb<<<g2, b2>>>(d, eta, d.divg, dt, d.etanew);
        }
        k_w_transport<<<g2, b2>>>(d, d.uit, d.vit, d.wf);
        advance_tracers(b, t, s, d.uit, d.vit, d.wf);
        k3_copy<<<g3, b3>>>(d, d.uit, u); k3_copy<<<g3, b3>>>(d, d.vit, v);
        k2_copy<<<g2, b2>>>(d, d.etanew, eta);
    }

    void step_split(double* u, double* v, double* b, double* eta, double* t, double* s) {
        const double dt = c.dt, f = c.f0, tc = c.theta_cor, thv = c.theta_v, ddt = dt / n_split;
        k_depth_transport<<<g2, b2>>>(d, u, d.dz3u, d.bu); k_depth_transport<<<g2, b2>>>(d, v, d.dz3v, d.bv);
        k3_copy<<<g3, b3>>>(d, u, d.uit); k3_copy<<<g3, b3>>>(d, v, d.vit);
        for (int m = 0; m < c.n_picard; ++m) {
            k_avg_v_to_u<<<g3, b3>>>(d, d.vit, d.mask3v, d.mask3u, d.vcor);
            k_avg_u_to_v<<<g3, b3>>>(d, d.uit, d.mask3u, d.mask3v, d.ucor);
            k3_predictor<<<g3, b3>>>(d, u, v, dt, f, tc, 0.0, thv, false, d.avpv, d.avpu, d.vcor, d.ucor, d.pgx, d.pgy, d.gx2, d.gy2, d.dzu, d.dzv, d.w3c, d.w3d, d.gu, d.gv);
            thomas(d.msub, d.mdiag, d.msup, d.gu, d.ghu); thomas(d.msub, d.mdiag, d.msup, d.gv, d.ghv);
            k3_copy<<<g3, b3>>>(d, d.ghu, d.uit); k3_copy<<<g3, b3>>>(d, d.ghv, d.vit);
        }
        /* Coriolis removed with the 2D transport operator the substeps add back (spec S8.3, N15) */
        k_depth_transport<<<g2, b2>>>(d, d.ghu, d.dz3u, d.umean); k_depth_transport<<<g2, b2>>>(d, d.ghv, d.dz3v, d.vmean);
        k2_avg_v_to_u<<<g2, b2>>>(d, d.bv, d.bavv); k2_avg_u_to_v<<<g2, b2>>>(d, d.bu, d.bavu);
        k2_avg_v_to_u<<<g2, b2>>>(d, d.vmean, d.bvcor); k2_avg_u_to_v<<<g2, b2>>>(d, d.umean, d.bucor);
        k2_cor_2d<<<g2, b2>>>(d, f, tc, d.bavv, d.bvcor, d.bavu, d.bucor, d.corx, d.cory);
        k2_baro_forcing<<<g2, b2>>>(d, d.umean, d.vmean, d.bu, d.bv, d.corx, d.cory, dt, d.bfx, d.bfy);
        for (int m = 0; m < n_split; ++m) {
            k2_avg_v_to_u<<<g2, b2>>>(d, d.bv, d.bavv); k2_avg_u_to_v<<<g2, b2>>>(d, d.bu, d.bavu);
            k2_grad<<<g2, b2>>>(d, eta, d.gx2, d.gy2);
            k2_copy<<<g2, b2>>>(d, d.bu, d.bui); k2_copy<<<g2, b2>>>(d, d.bv, d.bvi);
            for (int q = 0; q < c.n_picard; ++q) {
                k2_avg_v_to_u<<<g2, b2>>>(d, d.bvi, d.bvcor); k2_avg_u_to_v<<<g2, b2>>>(d, d.bui, d.bucor);
                k2_baro_mom<<<g2, b2>>>(d, d.bu, d.bv, d.bavv, d.bavu, d.bvcor, d.bucor, d.gx2, d.gy2, d.bfx, d.bfy, ddt, f, tc, c.g, d.bui, d.bvi);
            }
            k2_copy<<<g2, b2>>>(d, d.bui, d.bu); k2_copy<<<g2, b2>>>(d, d.bvi, d.bv);
            k2_div<<<g2, b2>>>(d, d.bu, d.bv, d.divg);
            k2_eta_dec<<<g2, b2>>>(d, eta, d.divg, ddt);
        }
        substeps += n_split;
        k3_split_correct<<<g3, b3>>>(d, d.ghu, d.ghv, d.umean, d.vmean, d.bu, d.bv, d.uit, d.vit);
        k_w_transport<<<g2, b2>>>(d, d.uit, d.vit, d.wf);
        advance_tracers(b, t, s, d.uit, d.vit, d.wf);
        k3_copy<<<g3, b3>>>(d, d.uit, u); k3_copy<<<g3, b3>>>(d, d.vit, v);
    }
};

/* --------------------------------------------------------------------- main */
static double median_of(std::vector<double> x)   /* fp64-io */ { std::sort(x.begin(), x.end()); size_t n = x.size(); return n % 2 ? x[n / 2] : 0.5 * (x[n / 2 - 1] + x[n / 2]); }
static std::string jnum(double x) { if (!std::isfinite(x)) return "null"; char b[64]; std::snprintf(b, sizeof b, "%.16e", x); return b; }

int main(int argc, char** argv) {
    if (argc < 2) { std::fprintf(stderr, "usage: cfd_exp3d5_cuda <namelist>\n"); return 1; }
    const RunConfig c = read_config(argv[1]);
    const V05Config v = read_v05(argv[1]);
    const int nx = c.nx, ny = c.ny, nz = c.nz, n2 = nx * ny, n3 = n2 * nz;
    const bool ts = v.tracers == "TS";
    cudaDeviceProp prop{}; CUDA_OK(cudaGetDeviceProperties(&prop, 0));

    /* The bundle on disk is fp64 in every build (R9): stage it, then convert to
     * the working precision. `fp64-io` marks the lines the fp32 generator keeps. */
    std::vector<double> io2(n2), io3(n3);                                   /* fp64-io */
    Domain dom; dom.h.resize(n2); dom.mask.resize(n2);
    { FILE* f = std::fopen(v.domain_file.c_str(), "rb");
      if (!f) { std::fprintf(stderr, "FATAL: cannot read %s\n", v.domain_file.c_str()); return 1; }
      std::fread(io2.data(), sizeof(double), n2, f);                        /* fp64-io */
      dom.h.assign(io2.begin(), io2.end());
      std::fread(io2.data(), sizeof(double), n2, f);                        /* fp64-io */
      dom.mask.assign(io2.begin(), io2.end());
      std::fclose(f); }
    dom.build(v, nx, ny, nz);

    std::vector<double> e0(n2), u0(n3), v0(n3), b0(n3), t0(n3, 0.0), s0(n3, 0.0);
    { FILE* f = std::fopen(v.init_file.c_str(), "rb");
      if (!f) { std::fprintf(stderr, "FATAL: cannot read %s\n", v.init_file.c_str()); return 1; }
      auto rd2 = [&](std::vector<double>& dst) { std::fread(dst.data(), sizeof(double), n2, f); };   /* fp64-io */
      auto rd3 = [&](std::vector<double>& dst) { std::fread(dst.data(), sizeof(double), n3, f); };   /* fp64-io */
      rd2(io2); e0.assign(io2.begin(), io2.end());
      rd3(io3); u0.assign(io3.begin(), io3.end());
      rd3(io3); v0.assign(io3.begin(), io3.end());
      rd3(io3); b0.assign(io3.begin(), io3.end());
      if (ts) { rd3(io3); t0.assign(io3.begin(), io3.end());
                rd3(io3); s0.assign(io3.begin(), io3.end()); }
      std::fclose(f); }

    double *d_u = dev_zero(n3), *d_v = dev_zero(n3), *d_b = dev_zero(n3), *d_t = dev_zero(n3), *d_s = dev_zero(n3), *d_eta = dev_zero(n2);
    size_t free_before = 0, free_after = 0, total_dev = 0;
    CUDA_OK(cudaMemGetInfo(&free_before, &total_dev));
    Stepper5 st(c, v, std::move(dom));
    CUDA_OK(cudaMemGetInfo(&free_after, &total_dev));
    const double dev_bytes = double(free_before - free_after);

    /* Divergence guard: a blown-up run (NaN or |eta| > 1e6 m) must not grind
     * through max_iter Helmholtz sweeps for hours; it is stopped and flagged. */
    double* d_part = dev_zero(1024); std::vector<double> h_part(1024);
    auto diverged = [&]() -> bool {
        int blocks = std::min(1024, (n2 + 255) / 256);
        k1_absmax<<<blocks, 256, 256 * sizeof(double)>>>(n2, d_eta, d_part);
        CUDA_OK(cudaMemcpy(h_part.data(), d_part, blocks * sizeof(double), cudaMemcpyDeviceToHost));
        double m = 0.0; for (int i = 0; i < blocks; ++i) { if (!(h_part[i] <= m)) m = h_part[i]; }
        return !(m < 1.0e6);
    };
    bool run_diverged = false;
    auto reset = [&]() {
        CUDA_OK(cudaMemcpy(d_u, u0.data(), n3 * sizeof(double), cudaMemcpyHostToDevice));
        CUDA_OK(cudaMemcpy(d_v, v0.data(), n3 * sizeof(double), cudaMemcpyHostToDevice));
        CUDA_OK(cudaMemcpy(d_b, b0.data(), n3 * sizeof(double), cudaMemcpyHostToDevice));
        CUDA_OK(cudaMemcpy(d_t, t0.data(), n3 * sizeof(double), cudaMemcpyHostToDevice));
        CUDA_OK(cudaMemcpy(d_s, s0.data(), n3 * sizeof(double), cudaMemcpyHostToDevice));
        CUDA_OK(cudaMemcpy(d_eta, e0.data(), n2 * sizeof(double), cudaMemcpyHostToDevice));
        if (st.is_tke) {                      /* TKE and the eddy coefficients are state too */
            std::vector<double> nu_i(st.d.n3i, c.nu), kap_i(st.d.n3i, c.kappa), tke0(st.d.n3i, v.e_min);
            CUDA_OK(cudaMemcpy(st.d.nu3, nu_i.data(), st.d.n3i * sizeof(double), cudaMemcpyHostToDevice));
            CUDA_OK(cudaMemcpy(st.d.kap3, kap_i.data(), st.d.n3i * sizeof(double), cudaMemcpyHostToDevice));
            CUDA_OK(cudaMemcpy(st.d.tke, tke0.data(), st.d.n3i * sizeof(double), cudaMemcpyHostToDevice));
            st.build_coefficients(false);
        }
    };
    std::printf("cuda3d5: case=%s nx=%d nz=%d scheme=%s solver=%s eos=%s dt=%12.5E steps=%d gpu=%s\n",
                c.case_name.c_str(), nx, nz, c.scheme_name.c_str(), c.solver_kind.c_str(), v.eos.c_str(), c.dt, c.n_steps, prop.name);
    for (int rep = 0; rep < c.n_warmup && !run_diverged; ++rep) {
        reset();
        for (int s = 0; s < c.n_steps; ++s) {
            st.step(d_u, d_v, d_b, d_eta, d_t, d_s);
            if (s == 0) CUDA_LAUNCH_OK("first step");
            if (s % 10 == 9 && diverged()) { run_diverged = true; break; }
        }
        CUDA_OK(cudaDeviceSynchronize());
        CUDA_LAUNCH_OK("warm-up repeat");
    }
    st.solver.total_iterations = 0; st.solver.failures = 0; st.substeps = 0; st.tridiag = 0;
    std::vector<double> samples;                 /* fp64-io */
    for (int rep = 0; rep < c.n_repeat; ++rep) {
        reset(); CUDA_OK(cudaDeviceSynchronize());
        auto t0c = std::chrono::steady_clock::now();
        for (int s = 0; s < c.n_steps; ++s) { st.step(d_u, d_v, d_b, d_eta, d_t, d_s); if (s % 10 == 9 && diverged()) { run_diverged = true; break; } }
        CUDA_OK(cudaDeviceSynchronize());
        auto t1c = std::chrono::steady_clock::now();
        CUDA_LAUNCH_OK("timed repeat");
        samples.push_back(std::chrono::duration<double>(t1c - t0c).count());
        if (run_diverged) { std::printf("  DIVERGED (|eta| > 1e6 or NaN) - run stopped early\n"); break; }
    }
    /* The loop breaks on divergence, so fewer than n_repeat repeats may have
     * run; dividing by n_repeat under-reports iterations per run by exactly
     * that factor, which can lift a diverged run back under the collector's
     * "iterations/step >= 2000" guard (docs/90 N33). */
    const int n_done = static_cast<int>(samples.size());
    const long iters = st.solver.total_iterations / std::max(1, n_done);
    const long subs = st.substeps / std::max(1, n_done);
    const double t_med = median_of(samples);
    std::vector<double> dev; for (double x : samples) dev.push_back(std::fabs(x - t_med));   /* fp64-io */
    const double t_mad = median_of(dev);

    std::vector<double> hu(n3), hv(n3), hb(n3), ht(n3), hs(n3), he(n2);
    CUDA_OK(cudaMemcpy(hu.data(), d_u, n3 * sizeof(double), cudaMemcpyDeviceToHost));
    CUDA_OK(cudaMemcpy(hv.data(), d_v, n3 * sizeof(double), cudaMemcpyDeviceToHost));
    CUDA_OK(cudaMemcpy(hb.data(), d_b, n3 * sizeof(double), cudaMemcpyDeviceToHost));
    CUDA_OK(cudaMemcpy(ht.data(), d_t, n3 * sizeof(double), cudaMemcpyDeviceToHost));
    CUDA_OK(cudaMemcpy(hs.data(), d_s, n3 * sizeof(double), cudaMemcpyDeviceToHost));
    CUDA_OK(cudaMemcpy(he.data(), d_eta, n2 * sizeof(double), cudaMemcpyDeviceToHost));
    std::printf("  wall median=%12.5E s  mad=%12.5E s  solver_iters/run=%ld  substeps/run=%ld\n", t_med, t_mad, iters, subs);

    const std::string bin = c.out_prefix + "_state3d5.bin";
    if (FILE* f = std::fopen(bin.c_str(), "wb")) {
        auto wr = [&](const std::vector<real_t_or_double>& a, int n) {                /* fp64-io */
            io3.assign(a.begin(), a.begin() + n);                                     /* fp64-io */
            std::fwrite(io3.data(), sizeof(double), n, f); };                         /* fp64-io */
        wr(he, n2); wr(hu, n3); wr(hv, n3); wr(hb, n3);
        if (ts) { wr(ht, n3); wr(hs, n3); }
        std::fclose(f);
    }
    const std::string mj = c.out_prefix + "_metrics.json";
    if (FILE* f = std::fopen(mj.c_str(), "w")) {
        std::fprintf(f, "{\n  \"backend\": \"cuda3d5\",\n  \"gpu\": \"%s\",\n  \"nx\": %d,\n  \"ny\": %d,\n  \"nz\": %d,\n  \"cells\": %d,\n"
                        "  \"n_steps\": %d,\n  \"scheme\": \"%s\",\n  \"solver\": \"%s\",\n  \"eos\": \"%s\",\n  \"advection\": \"%s\",\n"
                        "  \"tracers\": \"%s\",\n  \"theta\": %s,\n  \"dt\": %s,\n  \"solver_iterations\": %ld,\n  \"solver_failures\": %ld,\n"
                        "  \"tridiagonal_solves\": %ld,\n  \"solver_rebuilds\": %ld,\n  \"n_split\": %d,\n  \"barotropic_substeps\": %ld,\n  \"device_bytes\": %.0f,\n"
                        "  \"bytes_per_cell\": %s,\n  \"diverged\": %s,\n  \"wall_s\": %s,\n  \"wall_mad_s\": %s,\n  \"n_repeat\": %d,\n  \"omp_num_threads\": 0\n}\n",
                     prop.name, nx, ny, nz, n3, c.n_steps, c.scheme_name.c_str(), c.solver_kind.c_str(), v.eos.c_str(), v.advection.c_str(),
                     v.tracers.c_str(), jnum(c.theta).c_str(), jnum(c.dt).c_str(), iters, st.solver.failures, st.tridiag, st.rebuilds, st.n_split, subs,
                     dev_bytes, jnum(dev_bytes / n3).c_str(), run_diverged ? "true" : "false", jnum(t_med).c_str(), jnum(t_mad).c_str(), n_done);
        std::fclose(f);
    }
    return 0;
}
