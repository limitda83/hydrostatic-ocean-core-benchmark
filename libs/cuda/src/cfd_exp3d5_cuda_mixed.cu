/* --------------------------------------------------------------------- domain */
static double face_of(double a, double b, const std::string& rule) {
    if (rule == "mean") return 0.5 * (a + b);
    if (rule == "harmonic") return (a + b > 0.0) ? 2.0 * a * b / (a + b) : 0.0;
    return std::min(a, b);
}

struct Domain {  /* host copies, then uploaded */
    int nx, ny, nz;
    std::vector<double> h, mask, masku, maskv, hu, hv;
    std::vector<double> dz3, dz3u, dz3v, mask3, mask3u, mask3v, inv_dz3, zc, hcu, hcv, inv_hcu, inv_hcv;
    double hmax = 0.0;
    void build(const V05Config& v, int nx_, int ny_, int nz_) {
        nx = nx_; ny = ny_; nz = nz_;
        const int n2 = nx * ny, n3 = n2 * nz;
        masku.assign(n2, 0); maskv.assign(n2, 0); hu.assign(n2, 0); hv.assign(n2, 0);
        for (int j = 0; j < ny; ++j) for (int i = 0; i < nx; ++i) {
            int ip = (i + 1) % nx, jp = (j + 1) % ny, c = IDX2(i, j, nx);
            masku[c] = mask[c] * mask[IDX2(ip, j, nx)];
            maskv[c] = mask[c] * mask[IDX2(i, jp, nx)];
            if (v.bc_x != "periodic" && i == nx - 1) masku[c] = 0.0;
            if (v.bc_y != "periodic" && j == ny - 1) maskv[c] = 0.0;
            hu[c] = masku[c] * face_of(h[c], h[IDX2(ip, j, nx)], v.face_rule);
            hv[c] = maskv[c] * face_of(h[c], h[IDX2(i, jp, nx)], v.face_rule);
        }
        hmax = 0.0;
        for (int c = 0; c < n2; ++c) if (mask[c] > 0.0) hmax = std::max(hmax, h[c]);
        const double dzr = hmax / nz;
        dz3.assign(n3, 0); mask3.assign(n3, 0);
        for (int j = 0; j < ny; ++j) for (int i = 0; i < nx; ++i) {
            double edge = 0.0;
            for (int k = 0; k < nz; ++k) {
                double rem = h[IDX2(i, j, nx)] - edge;
                double th = std::min(std::max(rem, 0.0), dzr);
                if (th > 0.0 && th < v.min_partial * dzr) th = 0.0;
                if (mask[IDX2(i, j, nx)] <= 0.0) th = 0.0;
                dz3[IDX3(i, j, k, nx, ny)] = th;
                mask3[IDX3(i, j, k, nx, ny)] = th > 0.0 ? 1.0 : 0.0;
                edge += dzr;
            }
        }
        dz3u.assign(n3, 0); dz3v.assign(n3, 0); mask3u.assign(n3, 0); mask3v.assign(n3, 0);
        inv_dz3.assign(n3, 0); zc.assign(n3, 0);
        for (int k = 0; k < nz; ++k) for (int j = 0; j < ny; ++j) for (int i = 0; i < nx; ++i) {
            int ip = (i + 1) % nx, jp = (j + 1) % ny, c = IDX3(i, j, k, nx, ny);
            int ce = IDX3(ip, j, k, nx, ny), cn = IDX3(i, jp, k, nx, ny);
            mask3u[c] = mask3[c] * mask3[ce] * masku[IDX2(i, j, nx)];
            mask3v[c] = mask3[c] * mask3[cn] * maskv[IDX2(i, j, nx)];
            dz3u[c] = mask3u[c] * face_of(dz3[c], dz3[ce], v.face_rule);
            dz3v[c] = mask3v[c] * face_of(dz3[c], dz3[cn], v.face_rule);
            inv_dz3[c] = dz3[c] > 0.0 ? 1.0 / dz3[c] : 0.0;
        }
        for (int j = 0; j < ny; ++j) for (int i = 0; i < nx; ++i) {
            double above = 0.0;
            for (int k = 0; k < nz; ++k) {
                int c = IDX3(i, j, k, nx, ny);
                zc[c] = above + 0.5 * dz3[c];
                above += dz3[c];
            }
        }
        hcu.assign(n2, 0); hcv.assign(n2, 0); inv_hcu.assign(n2, 0); inv_hcv.assign(n2, 0);
        for (int j = 0; j < ny; ++j) for (int i = 0; i < nx; ++i) {
            int c2 = IDX2(i, j, nx);
            for (int k = 0; k < nz; ++k) { hcu[c2] += dz3u[IDX3(i, j, k, nx, ny)]; hcv[c2] += dz3v[IDX3(i, j, k, nx, ny)]; }
            inv_hcu[c2] = hcu[c2] > 0.0 ? 1.0 / hcu[c2] : 0.0;
            inv_hcv[c2] = hcv[c2] > 0.0 ? 1.0 / hcv[c2] : 0.0;
        }
    }
};

/* ---------------------------------------------------- variable Helmholtz */
struct HLevel {
    int nx = 0, ny = 0;
    double dx = 0, dy = 0;
    double *ku = nullptr, *kv = nullptr, *msk = nullptr, *dinv = nullptr, *x = nullptr, *b = nullptr, *r = nullptr;
};

__global__ void kh_dinv(HLevel lv, double coef) {
    int i = blockIdx.x * blockDim.x + threadIdx.x, j = blockIdx.y * blockDim.y + threadIdx.y;
    if (i >= lv.nx || j >= lv.ny) return;
    int im = wrapm(i, lv.nx), jm = wrapm(j, lv.ny);
    double cx = coef / (lv.dx * lv.dx), cy = coef / (lv.dy * lv.dy);
    double d = 1.0 + cx * (lv.ku[IDX2(i, j, lv.nx)] + lv.ku[IDX2(im, j, lv.nx)])
                   + cy * (lv.kv[IDX2(i, j, lv.nx)] + lv.kv[IDX2(i, jm, lv.nx)]);
    if (lv.msk[IDX2(i, j, lv.nx)] <= 0.0) d = 1.0;
    lv.dinv[IDX2(i, j, lv.nx)] = 1.0 / d;
}
__global__ void kh_apply(HLevel lv, double coef, const double* x, double* ax) {
    int i = blockIdx.x * blockDim.x + threadIdx.x, j = blockIdx.y * blockDim.y + threadIdx.y;
    if (i >= lv.nx || j >= lv.ny) return;
    int nx = lv.nx, ny = lv.ny, ip = wrapp(i, nx), im = wrapm(i, nx), jp = wrapp(j, ny), jm = wrapm(j, ny);
    double cx = coef / (lv.dx * lv.dx), cy = coef / (lv.dy * lv.dy), c = x[IDX2(i, j, nx)];
    double lap = cx * (lv.ku[IDX2(i, j, nx)] * (x[IDX2(ip, j, nx)] - c) - lv.ku[IDX2(im, j, nx)] * (c - x[IDX2(im, j, nx)]))
               + cy * (lv.kv[IDX2(i, j, nx)] * (x[IDX2(i, jp, nx)] - c) - lv.kv[IDX2(i, jm, nx)] * (c - x[IDX2(i, jm, nx)]));
    ax[IDX2(i, j, nx)] = lv.msk[IDX2(i, j, nx)] > 0.0 ? c - lap : c;
}
__global__ void kh_rbgs(HLevel lv, double coef, double* x, const double* b, int colour) {
    int i = blockIdx.x * blockDim.x + threadIdx.x, j = blockIdx.y * blockDim.y + threadIdx.y;
    if (i >= lv.nx || j >= lv.ny || ((i + j) & 1) != colour) return;
    int nx = lv.nx, ny = lv.ny;
    if (lv.msk[IDX2(i, j, nx)] <= 0.0) return;
    int ip = wrapp(i, nx), im = wrapm(i, nx), jp = wrapp(j, ny), jm = wrapm(j, ny);
    double cx = coef / (lv.dx * lv.dx), cy = coef / (lv.dy * lv.dy);
    double nb = cx * (lv.ku[IDX2(i, j, nx)] * x[IDX2(ip, j, nx)] + lv.ku[IDX2(im, j, nx)] * x[IDX2(im, j, nx)])
              + cy * (lv.kv[IDX2(i, j, nx)] * x[IDX2(i, jp, nx)] + lv.kv[IDX2(i, jm, nx)] * x[IDX2(i, jm, nx)]);
    x[IDX2(i, j, nx)] = lv.dinv[IDX2(i, j, nx)] * (b[IDX2(i, j, nx)] + nb);
}
__global__ void kh_residual(HLevel lv, const double* b, const double* ax, double* out) {
    int i = blockIdx.x * blockDim.x + threadIdx.x, j = blockIdx.y * blockDim.y + threadIdx.y;
    if (i >= lv.nx || j >= lv.ny) return;
    out[IDX2(i, j, lv.nx)] = (b[IDX2(i, j, lv.nx)] - ax[IDX2(i, j, lv.nx)]) * lv.msk[IDX2(i, j, lv.nx)];
}
__global__ void kh_restrict(HLevel f, HLevel c) {
    int i = blockIdx.x * blockDim.x + threadIdx.x, j = blockIdx.y * blockDim.y + threadIdx.y;
    if (i >= c.nx || j >= c.ny) return;
    c.b[IDX2(i, j, c.nx)] = 0.25 * (f.r[IDX2(2*i, 2*j, f.nx)] + f.r[IDX2(2*i+1, 2*j, f.nx)]
                                  + f.r[IDX2(2*i, 2*j+1, f.nx)] + f.r[IDX2(2*i+1, 2*j+1, f.nx)]);
    c.x[IDX2(i, j, c.nx)] = 0.0;
}
__global__ void kh_prolong(HLevel f, HLevel c) {
    int i = blockIdx.x * blockDim.x + threadIdx.x, j = blockIdx.y * blockDim.y + threadIdx.y;
    if (i >= f.nx || j >= f.ny) return;
    f.x[IDX2(i, j, f.nx)] += c.x[IDX2(i / 2, j / 2, c.nx)] * f.msk[IDX2(i, j, f.nx)];
}
/* Deterministic inner product: fixed grid-stride partials per block, then one
 * block folds the partials in a fixed order (no atomics, same bits every run). */
__global__ void kh_coarsen(HLevel f, HLevel c) {
    int i = blockIdx.x * blockDim.x + threadIdx.x, j = blockIdx.y * blockDim.y + threadIdx.y;
    if (i >= c.nx || j >= c.ny) return;
    c.ku[IDX2(i, j, c.nx)] = 0.5 * (f.ku[IDX2(2*i+1, 2*j, f.nx)] + f.ku[IDX2(2*i+1, 2*j+1, f.nx)]);
    c.kv[IDX2(i, j, c.nx)] = 0.5 * (f.kv[IDX2(2*i, 2*j+1, f.nx)] + f.kv[IDX2(2*i+1, 2*j+1, f.nx)]);
}
__global__ void k1_dot(int n, const double* a, const double* b, double* partial) {
    extern __shared__ double sh[];
    int tid = threadIdx.x; double s = 0.0;
    for (int t = blockIdx.x * blockDim.x + tid; t < n; t += blockDim.x * gridDim.x) s += a[t] * b[t];
    sh[tid] = s; __syncthreads();
    for (int k = blockDim.x / 2; k > 0; k >>= 1) { if (tid < k) sh[tid] += sh[tid + k]; __syncthreads(); }
    if (tid == 0) partial[blockIdx.x] = sh[0];
}
__global__ void k1_dot_final(int n_partial, const double* partial, double* out) {
    extern __shared__ double sh[];
    int tid = threadIdx.x; double s = 0.0;
    for (int t = tid; t < n_partial; t += blockDim.x) s += partial[t];
    sh[tid] = s; __syncthreads();
    for (int k = blockDim.x / 2; k > 0; k >>= 1) { if (tid < k) sh[tid] += sh[tid + k]; __syncthreads(); }
    if (tid == 0) *out = sh[0];
}
/* max |a| over n entries into partial[blockIdx] (one block folds later) */
__global__ void k1_absmax(int n, const double* a, double* partial) {
    extern __shared__ double sh[];
    int tid = threadIdx.x; double m = 0.0;
    for (int t = blockIdx.x * blockDim.x + tid; t < n; t += blockDim.x * gridDim.x) { double x = fabs(a[t]); if (!(x <= m)) m = x; }
    sh[tid] = m; __syncthreads();
    for (int k = blockDim.x / 2; k > 0; k >>= 1) { if (tid < k) { double x = sh[tid + k]; if (!(x <= sh[tid])) sh[tid] = x; } __syncthreads(); }
    if (tid == 0) partial[blockIdx.x] = sh[0];
}
