struct HelmVar {
    std::vector<HLevel> lv;
    int nx = 0, ny = 0, n = 0;
    double coef = 0, rtol = 1e-12; int max_iter = 2000;
    std::string kind = "pcg_jacobi";
    double *r = nullptr, *z = nullptr, *p = nullptr, *ap = nullptr, *scal = nullptr, *partial = nullptr;
    long total_iterations = 0, failures = 0;
    dim3 blk = dim3(32, 8);
    int TPB = 256, nblk = 0, dot_blocks = 0;

    void init(int nx_, int ny_, double dx, double dy, double coef_, const std::vector<double>& ku,
              const std::vector<double>& kv, const std::vector<double>& msk, const std::string& kind_,
              double rtol_, int max_iter_) {
        nx = nx_; ny = ny_; n = nx * ny; coef = coef_; rtol = rtol_; max_iter = max_iter_; kind = kind_;
        HLevel l0; l0.nx = nx; l0.ny = ny; l0.dx = dx; l0.dy = dy;
        l0.ku = dev_from(ku); l0.kv = dev_from(kv); l0.msk = dev_from(msk);
        lv.push_back(l0);
        if (kind == "multigrid") {
            std::vector<double> cku = ku, ckv = kv, cmsk = msk; int cnx = nx, cny = ny; double cdx = dx, cdy = dy;
            while (cnx % 2 == 0 && cny % 2 == 0 && cnx / 2 >= 8 && cny / 2 >= 8) {
                int mx = cnx / 2, my = cny / 2;
                std::vector<double> nku(mx * my), nkv(mx * my), nmsk(mx * my);
                for (int j = 0; j < my; ++j) for (int i = 0; i < mx; ++i) {
                    nku[IDX2(i, j, mx)] = 0.5 * (cku[IDX2(2*i+1, 2*j, cnx)] + cku[IDX2(2*i+1, 2*j+1, cnx)]);
                    nkv[IDX2(i, j, mx)] = 0.5 * (ckv[IDX2(2*i, 2*j+1, cnx)] + ckv[IDX2(2*i+1, 2*j+1, cnx)]);
                    double m = cmsk[IDX2(2*i, 2*j, cnx)];
                    m = std::max(m, cmsk[IDX2(2*i+1, 2*j, cnx)]); m = std::max(m, cmsk[IDX2(2*i, 2*j+1, cnx)]);
                    m = std::max(m, cmsk[IDX2(2*i+1, 2*j+1, cnx)]);
                    nmsk[IDX2(i, j, mx)] = m;
                }
                HLevel l; l.nx = mx; l.ny = my; l.dx = 2.0 * cdx; l.dy = 2.0 * cdy;
                l.ku = dev_from(nku); l.kv = dev_from(nkv); l.msk = dev_from(nmsk);
                lv.push_back(l);
                cku = nku; ckv = nkv; cmsk = nmsk; cnx = mx; cny = my; cdx *= 2; cdy *= 2;
            }
        }
        for (auto& l : lv) {
            size_t m = size_t(l.nx) * l.ny;
            l.dinv = dev_zero(m); l.x = dev_zero(m); l.b = dev_zero(m); l.r = dev_zero(m);
            kh_dinv<<<grid2(l.nx, l.ny, blk), blk>>>(l, coef);
        }
        nblk = (n + TPB - 1) / TPB; dot_blocks = std::min(nblk, 1024);
        r = dev_zero(n); z = dev_zero(n); p = dev_zero(n); ap = dev_zero(n); scal = dev_zero(1); partial = dev_zero(dot_blocks);
        CUDA_OK(cudaDeviceSynchronize());
    }
    /* New face coefficients on the device (masks unchanged): the per-step cost of
     * a step-dependent vertical viscosity under the theta scheme (S11.5). */
    void update(const double* d_ku, const double* d_kv) {
        CUDA_OK(cudaMemcpy(lv[0].ku, d_ku, n * sizeof(double), cudaMemcpyDeviceToDevice));
        CUDA_OK(cudaMemcpy(lv[0].kv, d_kv, n * sizeof(double), cudaMemcpyDeviceToDevice));
        kh_dinv<<<grid2(lv[0].nx, lv[0].ny, blk), blk>>>(lv[0], coef);
        for (size_t l = 1; l < lv.size(); ++l) {
            kh_coarsen<<<grid2(lv[l].nx, lv[l].ny, blk), blk>>>(lv[l - 1], lv[l]);
            kh_dinv<<<grid2(lv[l].nx, lv[l].ny, blk), blk>>>(lv[l], coef);
        }
    }
    double dot(const double* a, const double* b) {
        double out = 0.0;
        k1_dot<<<dot_blocks, TPB, TPB * sizeof(double)>>>(n, a, b, partial);
        k1_dot_final<<<1, TPB, TPB * sizeof(double)>>>(dot_blocks, partial, scal);
        CUDA_OK(cudaMemcpy(&out, scal, sizeof(double), cudaMemcpyDeviceToHost));
        return out;
    }
    void precondition(const double* rr, double* zz) {
        dim3 g0 = grid2(nx, ny, blk);
        if (kind == "pcg_rbgs") {
            k1_fill<<<nblk, TPB>>>(n, zz, 0.0);
            kh_rbgs<<<g0, blk>>>(lv[0], coef, zz, rr, 0); kh_rbgs<<<g0, blk>>>(lv[0], coef, zz, rr, 1);
            kh_rbgs<<<g0, blk>>>(lv[0], coef, zz, rr, 1); kh_rbgs<<<g0, blk>>>(lv[0], coef, zz, rr, 0);
        } else k1_jacobi<<<nblk, TPB>>>(n, lv[0].dinv, rr, zz);
    }
    void vcycle(int l) {
        HLevel& L = lv[l]; dim3 g = grid2(L.nx, L.ny, blk);
        for (int s = 0; s < 2; ++s) { kh_rbgs<<<g, blk>>>(L, coef, L.x, L.b, 0); kh_rbgs<<<g, blk>>>(L, coef, L.x, L.b, 1); }
        if (l + 1 < (int)lv.size()) {
            kh_apply<<<g, blk>>>(L, coef, L.x, L.r);
            kh_residual<<<g, blk>>>(L, L.b, L.r, L.r);
            HLevel& C = lv[l + 1];
            kh_restrict<<<grid2(C.nx, C.ny, blk), blk>>>(L, C);
            vcycle(l + 1);
            kh_prolong<<<g, blk>>>(L, C);
        }
        for (int s = 0; s < 2; ++s) { kh_rbgs<<<g, blk>>>(L, coef, L.x, L.b, 1); kh_rbgs<<<g, blk>>>(L, coef, L.x, L.b, 0); }
    }
    void solve(const double* rhs, double* x) {
        dim3 g0 = grid2(nx, ny, blk);
        int iters = 0; bool converged = true;
        k1_mulcopy<<<nblk, TPB>>>(n, rhs, lv[0].msk, r);
        double norm_b = std::sqrt(dot(r, r)), tol = rtol * norm_b;
        if (norm_b == 0.0) { k1_fill<<<nblk, TPB>>>(n, x, 0.0); return; }
        if (kind == "multigrid") {
            k1_fill<<<nblk, TPB>>>(n, lv[0].x, 0.0);
            k1_copy<<<nblk, TPB>>>(n, r, lv[0].b);
            converged = false;
            for (int it = 1; it <= max_iter; ++it) {
                vcycle(0);
                kh_apply<<<g0, blk>>>(lv[0], coef, lv[0].x, ap);
                kh_residual<<<g0, blk>>>(lv[0], lv[0].b, ap, r);
                iters = it;
                if (std::sqrt(dot(r, r)) <= tol) { converged = true; break; }
            }
            k1_copy<<<nblk, TPB>>>(n, lv[0].x, x);
        } else {
            k1_fill<<<nblk, TPB>>>(n, x, 0.0);
            precondition(r, z);
            k1_copy<<<nblk, TPB>>>(n, z, p);
            double rz = dot(r, z);
            converged = false;
            for (int it = 1; it <= max_iter; ++it) {
                kh_apply<<<g0, blk>>>(lv[0], coef, p, ap);
                double alpha = rz / dot(p, ap);
                k1_axpy2<<<nblk, TPB>>>(n, alpha, p, ap, x, r);
                iters = it;
                if (std::sqrt(dot(r, r)) <= tol) { converged = true; break; }
                precondition(r, z);
                double rzn = dot(r, z);
                k1_pupd<<<nblk, TPB>>>(n, rzn / rz, z, p);
                rz = rzn;
            }
        }
        total_iterations += iters;
        if (!converged) ++failures;
    }
};

