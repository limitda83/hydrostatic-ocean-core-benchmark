/* --- 2D kernels --- */
__global__ void k2_grad(Dev d, const double* eta, double* gx, double* gy) {
    COL2(d.nx, d.ny);
    int c = IDX2(i, j, d.nx);
    gx[c] = d.masku[c] * (eta[IDX2(wrapp(i, d.nx), j, d.nx)] - eta[c]) / d.dx;
    gy[c] = d.maskv[c] * (eta[IDX2(i, wrapp(j, d.ny), d.nx)] - eta[c]) / d.dy;
}
__global__ void k2_div(Dev d, const double* u, const double* v, double* out) {
    COL2(d.nx, d.ny);
    int c = IDX2(i, j, d.nx);
    out[c] = d.mask[c] * ((u[c] - u[IDX2(wrapm(i, d.nx), j, d.nx)]) / d.dx + (v[c] - v[IDX2(i, wrapm(j, d.ny), d.nx)]) / d.dy);
}
__global__ void k2_avg_v_to_u(Dev d, const double* v, double* out) {
    COL2(d.nx, d.ny);
    int ip = wrapp(i, d.nx), jm = wrapm(j, d.ny);
    int c = IDX2(i, j, d.nx), cs = IDX2(i, jm, d.nx), ce = IDX2(ip, j, d.nx), cse = IDX2(ip, jm, d.nx);
    double num = d.maskv[c] * v[c] + d.maskv[cs] * v[cs] + d.maskv[ce] * v[ce] + d.maskv[cse] * v[cse];
    double den = d.maskv[c] + d.maskv[cs] + d.maskv[ce] + d.maskv[cse];
    out[c] = den > 0.0 ? num / den * d.masku[c] : 0.0;
}
__global__ void k2_avg_u_to_v(Dev d, const double* u, double* out) {
    COL2(d.nx, d.ny);
    int im = wrapm(i, d.nx), jp = wrapp(j, d.ny);
    int c = IDX2(i, j, d.nx), cw = IDX2(im, j, d.nx), cn = IDX2(i, jp, d.nx), cnw = IDX2(im, jp, d.nx);
    double num = d.masku[c] * u[c] + d.masku[cw] * u[cw] + d.masku[cn] * u[cn] + d.masku[cnw] * u[cnw];
    double den = d.masku[c] + d.masku[cw] + d.masku[cn] + d.masku[cnw];
    out[c] = den > 0.0 ? num / den * d.maskv[c] : 0.0;
}
__global__ void k2_rhs_eta(Dev d, const double* eta, const double* divold, const double* divg, double dt, double th, double* rhs) {
    COL2(d.nx, d.ny); int c = IDX2(i, j, d.nx);
    rhs[c] = eta[c] - dt * ((1.0 - th) * divold[c] + th * divg[c]);
}
__global__ void k2_eta_fb(Dev d, const double* eta, const double* divg, double dt, double* out) {
    COL2(d.nx, d.ny); int c = IDX2(i, j, d.nx); out[c] = eta[c] - dt * divg[c];
}
__global__ void k2_copy(Dev d, const double* s, double* o) { COL2(d.nx, d.ny); int c = IDX2(i, j, d.nx); o[c] = s[c]; }
__global__ void k2_cor_int(Dev d, double f, double tc, const double* avpv, const double* vcor, const double* avpu, const double* ucor, double* corx, double* cory) {
    COL2(d.nx, d.ny);
    double cx = 0.0, cy = 0.0;
    for (int k = 0; k < d.nz; ++k) {
        int c = IDX3(i, j, k, d.nx, d.ny);
        cx += d.dz3u[c] * f * ((1.0 - tc) * avpv[c] + tc * vcor[c]);
        cy -= d.dz3v[c] * f * ((1.0 - tc) * avpu[c] + tc * ucor[c]);
    }
    corx[IDX2(i, j, d.nx)] = cx; cory[IDX2(i, j, d.nx)] = cy;
}
__global__ void k2_cor_2d(Dev d, double f, double tc, const double* av0, const double* avm, const double* au0, const double* aum, double* corx, double* cory) {
    COL2(d.nx, d.ny); int c = IDX2(i, j, d.nx);
    corx[c] = f * ((1.0 - tc) * av0[c] + tc * avm[c]);
    cory[c] = -f * ((1.0 - tc) * au0[c] + tc * aum[c]);
}
__global__ void k2_baro_forcing(Dev d, const double* umean, const double* vmean, const double* bu, const double* bv, const double* corx, const double* cory, double dt, double* bfx, double* bfy) {
    COL2(d.nx, d.ny); int c = IDX2(i, j, d.nx);
    bfx[c] = (umean[c] - bu[c]) / dt - corx[c]; bfy[c] = (vmean[c] - bv[c]) / dt - cory[c];
}
__global__ void k2_baro_mom(Dev d, const double* bu, const double* bv, const double* bavv, const double* bavu, const double* bvcor, const double* bucor,
                            const double* gx2, const double* gy2, const double* bfx, const double* bfy, double ddt, double f, double tc, double g_, double* bui, double* bvi) {
    COL2(d.nx, d.ny); int c = IDX2(i, j, d.nx);
    bui[c] = (bu[c] + ddt * (f * ((1.0 - tc) * bavv[c] + tc * bvcor[c]) - g_ * d.ku[c] * gx2[c] + bfx[c])) * d.masku[c];
    bvi[c] = (bv[c] + ddt * (-f * ((1.0 - tc) * bavu[c] + tc * bucor[c]) - g_ * d.kv[c] * gy2[c] + bfy[c])) * d.maskv[c];
}
__global__ void k2_eta_dec(Dev d, double* eta, const double* divg, double ddt) { COL2(d.nx, d.ny); int c = IDX2(i, j, d.nx); eta[c] -= ddt * divg[c]; }

