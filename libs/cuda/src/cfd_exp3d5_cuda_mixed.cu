/* --- vertical / column kernels --- */
__global__ void k_diff_coeffs(Dev d, double thv, double dt, const double* nu3, double drag,
                              const double* dz3, double* sub, double* diag, double* sup) {
    GRID3(d.nx, d.ny, d.nz);
    const int c = IDX3(i, j, k, d.nx, d.ny), nz = d.nz;
    const double nu_t = nu3[c], nu_b2 = nu3[c + d.n2];        /* interfaces above / below layer k */
    bool dry = d.mask3[c] <= 0.0;
    bool bottom = !dry && (k == nz - 1 || d.mask3[IDX3(i, j, k + 1, d.nx, d.ny)] <= 0.0);
    double inv_dz = d.inv_dz3[c];
    double dzt = (k == 0) ? dz3[c] : 0.5 * (dz3[IDX3(i, j, k - 1, d.nx, d.ny)] + dz3[c]);
    double dzb = (k == nz - 1) ? dz3[c] : 0.5 * (dz3[c] + dz3[IDX3(i, j, k + 1, d.nx, d.ny)]);
    double at = thv * dt * inv_dz * nu_t * safe_inv(dzt), ab = thv * dt * inv_dz * nu_b2 * safe_inv(dzb);
    double s = -at, u = -ab, g = 1.0 + at + ab;
    if (k == 0) { g = 1.0 + ab; s = 0.0; }
    if (bottom) { g = 1.0 + at + thv * dt * drag * inv_dz; u = 0.0; }
    if (dry) { g = 1.0; s = 0.0; u = 0.0; }
    sub[c] = s; diag[c] = g; sup[c] = u;
}
__global__ void k_thomas(const double* sub, const double* diag, const double* sup, const double* rhs,
                         double* x, double* cstar, int nx, int ny, int nz) {
    COL2(nx, ny);
    int c = IDX3(i, j, 0, nx, ny); const int st = nx * ny;
    cstar[c] = sup[c] / diag[c]; x[c] = rhs[c] / diag[c];
    for (int k = 1; k < nz; ++k) {
        int cp = c; c += st;
        double den = diag[c] - sub[c] * cstar[cp];
        cstar[c] = sup[c] / den; x[c] = (rhs[c] - sub[c] * x[cp]) / den;
    }
    for (int k = nz - 2; k >= 0; --k) { c -= st; x[c] -= cstar[c] * x[c + st]; }
}
__global__ void k_apply_diff(Dev d, const double* f, const double* nu3, const double* dzx, const double* sflux, double drag, double* out) {
    GRID3(d.nx, d.ny, d.nz);
    const int c = IDX3(i, j, k, d.nx, d.ny), nz = d.nz;
    bool here = d.mask3[c] > 0.0 && (k == nz - 1 || d.mask3[IDX3(i, j, k + 1, d.nx, d.ny)] <= 0.0);
    double ftop, fbot;
    if (k == 0) ftop = sflux[IDX2(i, j, d.nx)];
    else {
        int cu = IDX3(i, j, k - 1, d.nx, d.ny);
        bool above = d.mask3[cu] > 0.0 && d.mask3[c] <= 0.0;
        double dzi = 0.5 * (dzx[cu] + dzx[c]);
        ftop = nu3[c] * (f[cu] - f[c]) * safe_inv(dzi);
        if (above) ftop = 0.0;
    }
    if (k == nz - 1) fbot = 0.0;
    else {
        int cd = IDX3(i, j, k + 1, d.nx, d.ny);
        double dzi = 0.5 * (dzx[c] + dzx[cd]);
        fbot = nu3[c + d.n2] * (f[c] - f[cd]) * safe_inv(dzi);
        if (here) fbot = 0.0;
    }
    double o = (ftop - fbot) * safe_inv(dzx[c]);
    if (here) o -= drag * f[c] * safe_inv(dzx[c]);
    if (d.mask3[c] <= 0.0) o = 0.0;
    out[c] = o;
}
__global__ void k_w_transport(Dev d, const double* u, const double* v, double* wf) {
    COL2(d.nx, d.ny);
    int im = wrapm(i, d.nx), jm = wrapm(j, d.ny), nz = d.nz;
    wf[IDX3(i, j, nz, d.nx, d.ny)] = 0.0;
    for (int k = nz - 1; k >= 0; --k) {
        int c = IDX3(i, j, k, d.nx, d.ny), cw = IDX3(im, j, k, d.nx, d.ny), cs = IDX3(i, jm, k, d.nx, d.ny);
        double dv = ((d.dz3u[c] * u[c] - d.dz3u[cw] * u[cw]) / d.dx + (d.dz3v[c] * v[c] - d.dz3v[cs] * v[cs]) / d.dy) * d.mask3[c];
        wf[c] = wf[IDX3(i, j, k + 1, d.nx, d.ny)] - dv;
    }
}
__global__ void k_depth_transport(Dev d, const double* u, const double* dzx, double* out) {
    COL2(d.nx, d.ny);
    double s = 0.0;
    for (int k = 0; k < d.nz; ++k) { int c = IDX3(i, j, k, d.nx, d.ny); s += dzx[c] * u[c]; }
    out[IDX2(i, j, d.nx)] = s;
}
__global__ void k_phi(Dev d, const double* b, bool do_remove, double* phi) {
    COL2(d.nx, d.ny);
    double above = 0.0, tot = 0.0, mean = 0.0;
    for (int k = 0; k < d.nz; ++k) {
        int c = IDX3(i, j, k, d.nx, d.ny);
        phi[c] = 0.5 * d.dz3[c] * b[c] + above;
        above += d.dz3[c] * b[c]; tot += d.dz3[c]; mean += d.dz3[c] * phi[c];
    }
    if (do_remove) { mean *= safe_inv(tot); for (int k = 0; k < d.nz; ++k) phi[IDX3(i, j, k, d.nx, d.ny)] -= mean; }
}
/* --- 3D horizontal kernels --- */
__global__ void k_pg(Dev d, const double* b, const double* phi, bool corr, double* pgx, double* pgy) {
    GRID3(d.nx, d.ny, d.nz);
    const int c = IDX3(i, j, k, d.nx, d.ny), ce = IDX3(wrapp(i, d.nx), j, k, d.nx, d.ny), cn = IDX3(i, wrapp(j, d.ny), k, d.nx, d.ny);
    if (corr) {
        double zf = 0.5 * (d.zc[c] + d.zc[ce]);
        double l = phi[c] + b[c] * (zf - d.zc[c]), r = phi[ce] + b[ce] * (zf - d.zc[ce]);
        pgx[c] = d.mask3u[c] * (r - l) / d.dx;
        zf = 0.5 * (d.zc[c] + d.zc[cn]);
        l = phi[c] + b[c] * (zf - d.zc[c]); r = phi[cn] + b[cn] * (zf - d.zc[cn]);
        pgy[c] = d.mask3v[c] * (r - l) / d.dy;
    } else {
        pgx[c] = d.mask3u[c] * (phi[ce] - phi[c]) / d.dx;
        pgy[c] = d.mask3v[c] * (phi[cn] - phi[c]) / d.dy;
    }
}
__global__ void k_avg_v_to_u(Dev d, const double* v, const double* mv, const double* mu, double* out) {
    GRID3(d.nx, d.ny, d.nz);
    int ip = wrapp(i, d.nx), jm = wrapm(j, d.ny);
    int c = IDX3(i, j, k, d.nx, d.ny), cs = IDX3(i, jm, k, d.nx, d.ny), ce = IDX3(ip, j, k, d.nx, d.ny), cse = IDX3(ip, jm, k, d.nx, d.ny);
    double num = mv[c] * v[c] + mv[cs] * v[cs] + mv[ce] * v[ce] + mv[cse] * v[cse];
    double den = mv[c] + mv[cs] + mv[ce] + mv[cse];
    out[c] = den > 0.0 ? num / den * mu[c] : 0.0;
}
__global__ void k_avg_u_to_v(Dev d, const double* u, const double* mu, const double* mv, double* out) {
    GRID3(d.nx, d.ny, d.nz);
    int im = wrapm(i, d.nx), jp = wrapp(j, d.ny);
    int c = IDX3(i, j, k, d.nx, d.ny), cw = IDX3(im, j, k, d.nx, d.ny), cn = IDX3(i, jp, k, d.nx, d.ny), cnw = IDX3(im, jp, k, d.nx, d.ny);
    double num = mu[c] * u[c] + mu[cw] * u[cw] + mu[cn] * u[cn] + mu[cnw] * u[cnw];
    double den = mu[c] + mu[cw] + mu[cn] + mu[cnw];
    out[c] = den > 0.0 ? num / den * mv[c] : 0.0;
}
__global__ void k_lap_m(Dev d, const double* a, const double* mu, const double* mv, const double* mc, double* out) {
    GRID3(d.nx, d.ny, d.nz);
    int ip = wrapp(i, d.nx), im = wrapm(i, d.nx), jp = wrapp(j, d.ny), jm = wrapm(j, d.ny);
    int c = IDX3(i, j, k, d.nx, d.ny), ce = IDX3(ip, j, k, d.nx, d.ny), cw = IDX3(im, j, k, d.nx, d.ny), cn = IDX3(i, jp, k, d.nx, d.ny), cs = IDX3(i, jm, k, d.nx, d.ny);
    double fxe = mu[c] * (a[ce] - a[c]) / d.dx, fxw = mu[cw] * (a[c] - a[cw]) / d.dx;
    double fyn = mv[c] * (a[cn] - a[c]) / d.dy, fys = mv[cs] * (a[c] - a[cs]) / d.dy;
    out[c] = mc[c] * ((fxe - fxw) / d.dx + (fyn - fys) / d.dy);
}
__global__ void k_mom_adv(Dev d, const double* u, const double* v, const double* wf, double dz_nom, double* exu, double* exv) {
    GRID3(d.nx, d.ny, d.nz);
    int ip = wrapp(i, d.nx), im = wrapm(i, d.nx), jp = wrapp(j, d.ny), jm = wrapm(j, d.ny), nz = d.nz;
    auto A = [&](int ii, int jj, int kk) { return IDX3(ii, jj, kk, d.nx, d.ny); };
    int c = A(i, j, k);
    double ubc = 0.5 * (u[A(im, j, k)] + u[c]), ubc_e = 0.5 * (u[c] + u[A(ip, j, k)]);
    double fyu_n = 0.5 * (v[c] + v[A(ip, j, k)]) * 0.5 * (u[c] + u[A(i, jp, k)]);
    double fyu_s = 0.5 * (v[A(i, jm, k)] + v[A(ip, jm, k)]) * 0.5 * (u[A(i, jm, k)] + u[c]);
    double fzt = 0.0, fzb = 0.0, wb;
    if (k > 0) { wb = 0.5 * (wf[A(i, j, k)] + wf[A(ip, j, k)]); fzt = wb * 0.5 * (u[A(i, j, k - 1)] + u[c]); }
    if (k < nz - 1) { wb = 0.5 * (wf[A(i, j, k + 1)] + wf[A(ip, j, k + 1)]); fzb = wb * 0.5 * (u[c] + u[A(i, j, k + 1)]); }
    exu[c] -= d.mask3u[c] * ((ubc_e * ubc_e - ubc * ubc) / d.dx + (fyu_n - fyu_s) / d.dy + (fzt - fzb) / dz_nom);
    double vbc = 0.5 * (v[A(i, jm, k)] + v[c]), vbc_n = 0.5 * (v[c] + v[A(i, jp, k)]);
    double fxv_e = 0.5 * (u[c] + u[A(i, jp, k)]) * 0.5 * (v[c] + v[A(ip, j, k)]);
    double fxv_w = 0.5 * (u[A(im, j, k)] + u[A(im, jp, k)]) * 0.5 * (v[A(im, j, k)] + v[c]);
    fzt = 0.0; fzb = 0.0;
    if (k > 0) { wb = 0.5 * (wf[A(i, j, k)] + wf[A(i, jp, k)]); fzt = wb * 0.5 * (v[A(i, j, k - 1)] + v[c]); }
    if (k < nz - 1) { wb = 0.5 * (wf[A(i, j, k + 1)] + wf[A(i, jp, k + 1)]); fzb = wb * 0.5 * (v[c] + v[A(i, j, k + 1)]); }
    exv[c] -= d.mask3v[c] * ((vbc_n * vbc_n - vbc * vbc) / d.dy + (fxv_e - fxv_w) / d.dx + (fzt - fzb) / dz_nom);
}
/* Third-order upwind-biased face value (spec S11.3): the face between c and cp
 * for the advecting velocity vel; cm = c[i-1], cpp = c[i+2]; ok_* say whether
 * the far cell is wet (else first-order upwind). */
__device__ __forceinline__ double kface(double cm, double c, double cp, double cpp, double vel,
                                        bool ok_pos, bool ok_neg, bool limited) {
    const double KAP = 1.0 / 3.0;
    double f_pos, f_neg;
    if (limited) {
        double dc = cp - c, r_pos = 0.0, r_neg = 0.0;
        if (dc != 0.0) { r_pos = (c - cm) / dc; r_neg = (cpp - cp) / dc; }
        double phi_pos = fmax(0.0, fmax(fmin(2.0 * r_pos, 1.0), fmin(r_pos, 2.0)));
        double phi_neg = fmax(0.0, fmax(fmin(2.0 * r_neg, 1.0), fmin(r_neg, 2.0)));
        f_pos = c + 0.5 * phi_pos * dc;
        f_neg = cp - 0.5 * phi_neg * dc;
    } else {
        f_pos = c + 0.25 * ((1.0 - KAP) * (c - cm) + (1.0 + KAP) * (cp - c));
        f_neg = cp - 0.25 * ((1.0 - KAP) * (cpp - cp) + (1.0 + KAP) * (cp - c));
    }
    if (!ok_pos) f_pos = c;
    if (!ok_neg) f_neg = cp;
    return vel > 0.0 ? f_pos : f_neg;
}
__device__ __forceinline__ int wrapp2(int i, int n) { return wrapp(wrapp(i, n), n); }
__device__ __forceinline__ int wrapm2(int i, int n) { return wrapm(wrapm(i, n), n); }

__global__ void k_mom_adv_up3(Dev d, const double* u, const double* v, const double* wf, double dz_nom, bool lim, double* exu, double* exv) {
    GRID3(d.nx, d.ny, d.nz);
    const int nx = d.nx, ny = d.ny, nz = d.nz;
    int ip = wrapp(i, nx), im = wrapm(i, nx), ipp = wrapp2(i, nx), imm = wrapm2(i, nx);
    int jp = wrapp(j, ny), jm = wrapm(j, ny), jpp = wrapp2(j, ny), jmm = wrapm2(j, ny);
    auto A = [&](int ii, int jj, int kk) { return IDX3(ii, jj, kk, nx, ny); };
    auto U = [&](int ii, int jj, int kk) { return (kk >= 0 && kk < nz) ? u[A(ii, jj, kk)] : 0.0; };
    auto V = [&](int ii, int jj, int kk) { return (kk >= 0 && kk < nz) ? v[A(ii, jj, kk)] : 0.0; };
    auto MU = [&](int ii, int jj, int kk) { return (kk >= 0 && kk < nz) && d.mask3u[A(ii, jj, kk)] > 0.0; };
    auto MV = [&](int ii, int jj, int kk) { return (kk >= 0 && kk < nz) && d.mask3v[A(ii, jj, kk)] > 0.0; };
    const int c = A(i, j, k);
    /* ---- u */
    double ubc = 0.5 * (u[A(im, j, k)] + u[c]), ubc_e = 0.5 * (u[c] + u[A(ip, j, k)]);
    double uac = kface(u[A(imm, j, k)], u[A(im, j, k)], u[c], u[A(ip, j, k)], ubc, MU(imm, j, k), MU(ip, j, k), lim);
    double uac_e = kface(u[A(im, j, k)], u[c], u[A(ip, j, k)], u[A(ipp, j, k)], ubc_e, MU(im, j, k), MU(ipp, j, k), lim);
    double vbar = 0.5 * (v[c] + v[A(ip, j, k)]), vbar_s = 0.5 * (v[A(i, jm, k)] + v[A(ip, jm, k)]);
    double uay = kface(u[A(i, jm, k)], u[c], u[A(i, jp, k)], u[A(i, jpp, k)], vbar, MU(i, jm, k), MU(i, jpp, k), lim);
    double uay_s = kface(u[A(i, jmm, k)], u[A(i, jm, k)], u[c], u[A(i, jp, k)], vbar_s, MU(i, jmm, k), MU(i, jp, k), lim);
    double fzt = 0.0, fzb = 0.0, wb;
    if (k > 0) { wb = 0.5 * (wf[A(i, j, k)] + wf[A(ip, j, k)]);
                 fzt = wb * kface(U(i, j, k + 1), u[c], u[A(i, j, k - 1)], U(i, j, k - 2), wb, MU(i, j, k + 1), MU(i, j, k - 2), lim); }
    if (k < nz - 1) { wb = 0.5 * (wf[A(i, j, k + 1)] + wf[A(ip, j, k + 1)]);
                      fzb = wb * kface(U(i, j, k + 2), u[A(i, j, k + 1)], u[c], U(i, j, k - 1), wb, MU(i, j, k + 2), MU(i, j, k - 1), lim); }
    exu[c] -= d.mask3u[c] * ((ubc_e * uac_e - ubc * uac) / d.dx + (vbar * uay - vbar_s * uay_s) / d.dy + (fzt - fzb) / dz_nom);
    /* ---- v */
    double vbc = 0.5 * (v[A(i, jm, k)] + v[c]), vbc_n = 0.5 * (v[c] + v[A(i, jp, k)]);
    double vac = kface(v[A(i, jmm, k)], v[A(i, jm, k)], v[c], v[A(i, jp, k)], vbc, MV(i, jmm, k), MV(i, jp, k), lim);
    double vac_n = kface(v[A(i, jm, k)], v[c], v[A(i, jp, k)], v[A(i, jpp, k)], vbc_n, MV(i, jm, k), MV(i, jpp, k), lim);
    double ubar = 0.5 * (u[c] + u[A(i, jp, k)]), ubar_w = 0.5 * (u[A(im, j, k)] + u[A(im, jp, k)]);
    double vax = kface(v[A(im, j, k)], v[c], v[A(ip, j, k)], v[A(ipp, j, k)], ubar, MV(im, j, k), MV(ipp, j, k), lim);
    double vax_w = kface(v[A(imm, j, k)], v[A(im, j, k)], v[c], v[A(ip, j, k)], ubar_w, MV(imm, j, k), MV(ip, j, k), lim);
    fzt = 0.0; fzb = 0.0;
    if (k > 0) { wb = 0.5 * (wf[A(i, j, k)] + wf[A(i, jp, k)]);
                 fzt = wb * kface(V(i, j, k + 1), v[c], v[A(i, j, k - 1)], V(i, j, k - 2), wb, MV(i, j, k + 1), MV(i, j, k - 2), lim); }
    if (k < nz - 1) { wb = 0.5 * (wf[A(i, j, k + 1)] + wf[A(i, jp, k + 1)]);
                      fzb = wb * kface(V(i, j, k + 2), v[A(i, j, k + 1)], v[c], V(i, j, k - 1), wb, MV(i, j, k + 2), MV(i, j, k - 1), lim); }
    exv[c] -= d.mask3v[c] * ((vbc_n * vac_n - vbc * vac) / d.dy + (ubar * vax - ubar_w * vax_w) / d.dx + (fzt - fzb) / dz_nom);
}

/* One column per thread: spec S11.2 / closure.py (mirrors mod_model3d_v05::closure_step). */
#define MAXNZ1 65
__global__ void k_closure(Dev d, const double* u, const double* v, const double* b, double dt, double nu_b, double kap_b,
                          double ustar2, double c_k, double c_eps, double pr_t, double z_0, double e_min, double l_min, double e_bb,
                          double n2_min, bool mxl_recursive) {
    COL2(d.nx, d.ny);
    const int nx = d.nx, ny = d.ny, nz = d.nz, n2 = d.n2;
    if (nz + 1 > MAXNZ1) return;
    int im = wrapm(i, nx), jm = wrapm(j, ny);
    closure_t zs[MAXNZ1], zb[MAXNZ1], wet[MAXNZ1], dzi[MAXNZ1], n2a[MAXNZ1], sh2[MAXNZ1];
    closure_t lup[MAXNZ1], ldn[MAXNZ1], lk[MAXNZ1], leps[MAXNZ1];
    closure_t sub[MAXNZ1], dia[MAXNZ1], sup[MAXNZ1], rhs[MAXNZ1], cst[MAXNZ1], xx[MAXNZ1];
    auto C = [&](int kk) { return IDX3(i, j, kk, nx, ny); };
    auto CI = [&](int kk) { return IDX3(i, j, kk, nx, ny); };  /* interface arrays share the layout */
    zs[0] = RC(0.0);
    for (int k = 0; k < nz; ++k) zs[k + 1] = zs[k] + RC(d.dz3[C(k)]);
    closure_t hcol = zs[nz];
    for (int k = 0; k <= nz; ++k) { zb[k] = fmax(hcol - zs[k], RC(0.0)); wet[k] = RC(0.0); n2a[k] = RC(0.0); sh2[k] = RC(0.0); }
    dzi[0] = RC(d.dz3[C(0)]); dzi[nz] = RC(d.dz3[C(nz - 1)]);
    for (int k = 1; k < nz; ++k) {
        dzi[k] = RC(0.5) * (RC(d.dz3[C(k - 1)]) + RC(d.dz3[C(k)]));
        wet[k] = RC(d.mask3[C(k - 1)]) * RC(d.mask3[C(k)]);
        closure_t inv_dzi = RC(safe_inv(dzi[k]));
        closure_t uc_a = RC(0.5) * (RC(u[C(k - 1)]) + RC(u[IDX3(im, j, k - 1, nx, ny)])), uc_b = RC(0.5) * (RC(u[C(k)]) + RC(u[IDX3(im, j, k, nx, ny)]));
        closure_t vc_a = RC(0.5) * (RC(v[C(k - 1)]) + RC(v[IDX3(i, jm, k - 1, nx, ny)])), vc_b = RC(0.5) * (RC(v[C(k)]) + RC(v[IDX3(i, jm, k, nx, ny)]));
        closure_t du = (uc_a - uc_b) * inv_dzi, dv = (vc_a - vc_b) * inv_dzi;
        sh2[k] = (du * du + dv * dv) * wet[k];
        n2a[k] = ((RC(b[C(k - 1)]) - RC(b[C(k)])) * inv_dzi) * wet[k];
    }
    for (int k = 0; k <= nz; ++k) { lup[k] = RC(0.0); ldn[k] = RC(0.0); }
    if (mxl_recursive) {
        /* S11.2 `recursive`: buoyancy length capped by the walls, then limited to
         * grow no faster than the grid by one downward and one upward sweep.
         * Two O(nz) passes instead of the O(nz^2) energy budget below. */
        for (int k = 0; k <= nz; ++k) {
            closure_t n2c = fmax(n2a[k], RC(n2_min));
            closure_t l = sqrt(RC(2.0) * fmax(RC(d.tke[CI(k)]), RC(e_min)) / n2c);
            lup[k] = fmin(l, fmin(zs[k] + RC(z_0), zb[k] + RC(z_0)));
        }
        for (int k = 1; k <= nz; ++k) lup[k] = fmin(lup[k], lup[k - 1] + dzi[k]);
        for (int k = nz - 1; k >= 0; --k) lup[k] = fmin(lup[k], lup[k + 1] + dzi[k + 1]);
        for (int k = 0; k <= nz; ++k) { lup[k] *= wet[k]; ldn[k] = lup[k]; }
    } else
    for (int dir = 1; dir <= 2; ++dir) {
        for (int k = 0; k <= nz; ++k) {
            closure_t l = RC(0.0), budget = fmax(RC(d.tke[CI(k)]), RC(e_min));
            for (int jj = 1; jj <= nz; ++jj) {
                int kk = (dir == 1) ? k - jj : k + jj;
                closure_t n2_j = RC(0.0), dz_j = RC(0.0);
                if (kk >= 0 && kk <= nz) { n2_j = fmax(n2a[kk], RC(0.0)); dz_j = dzi[kk]; }
                closure_t cost = n2_j * dz_j * (l + RC(0.5) * dz_j);
                closure_t aa = (n2_j > RC(0.0)) ? n2_j : RC(1.0);
                closure_t s_part = sqrt(fmax(l * l + RC(2.0) * budget / aa, RC(0.0))) - l;
                closure_t step;
                if (cost <= budget) step = dz_j;
                else if (n2_j > RC(0.0)) step = fmin(fmax(s_part, RC(0.0)), dz_j);
                else step = dz_j;
                if (budget > RC(0.0)) l += step;
                budget = (cost <= budget) ? budget - cost : RC(0.0);
            }
            if (dir == 1) lup[k] = fmin(l, zs[k] + RC(z_0)) * wet[k]; else ldn[k] = fmin(l, zb[k] + RC(z_0)) * wet[k];
        }
    }
    for (int k = 0; k <= nz; ++k) { lk[k] = fmax(RC(l_min), sqrt(lup[k] * ldn[k])); leps[k] = fmax(RC(l_min), fmin(lup[k], ldn[k])); }
    closure_t e_surf = RC(e_bb) * RC(ustar2);
    for (int k = 0; k <= nz; ++k) {
        closure_t prod = (RC(d.nu3[CI(k)]) - RC(nu_b)) * sh2[k] - (RC(d.kap3[CI(k)]) - RC(kap_b)) * n2a[k];
        closure_t diss = RC(c_eps) * sqrt(fmax(RC(d.tke[CI(k)]), RC(e_min))) / leps[k];
        closure_t a_up = RC(0.0), a_dn = RC(0.0);
        if (k >= 1 && k <= nz - 1) {
            closure_t klay_a = RC(0.5) * (RC(d.nu3[CI(k - 1)]) + RC(d.nu3[CI(k)])), klay_b = RC(0.5) * (RC(d.nu3[CI(k)]) + RC(d.nu3[CI(k + 1)]));
            closure_t inv_dzi = RC(safe_inv(dzi[k]));
            a_up = RC(dt) * klay_a * RC(safe_inv(RC(d.dz3[C(k - 1)]))) * inv_dzi;
            a_dn = RC(dt) * klay_b * RC(safe_inv(RC(d.dz3[C(k)]))) * inv_dzi;
        }
        sub[k] = -a_up; sup[k] = -a_dn; dia[k] = RC(1.0) + a_up + a_dn + RC(dt) * diss; rhs[k] = RC(d.tke[CI(k)]) + RC(dt) * prod;
        if (wet[k] <= RC(0.0)) { dia[k] = RC(1.0); sub[k] = RC(0.0); sup[k] = RC(0.0); rhs[k] = RC(e_min); }
    }
    rhs[0] = (RC(d.mask3[C(0)]) > RC(0.0)) ? e_surf : RC(e_min);
    cst[0] = sup[0] / dia[0]; xx[0] = rhs[0] / dia[0];
    for (int k = 1; k <= nz; ++k) { closure_t den = dia[k] - sub[k] * cst[k - 1]; cst[k] = sup[k] / den; xx[k] = (rhs[k] - sub[k] * xx[k - 1]) / den; }
    for (int k = nz - 1; k >= 0; --k) xx[k] -= cst[k] * xx[k + 1];
    for (int k = 0; k <= nz; ++k) { xx[k] = fmax(xx[k], RC(e_min)); if (wet[k] <= RC(0.0)) xx[k] = RC(e_min); }
    xx[0] = rhs[0];
    for (int k = 0; k <= nz; ++k) {
        d.tke[CI(k)] = xx[k];
        closure_t km = RC(c_k) * lk[k] * sqrt(xx[k]) * wet[k] + RC(nu_b);
        d.nu3[CI(k)] = km;
        d.kap3[CI(k)] = (km - RC(nu_b)) / RC(pr_t) + RC(kap_b);
    }
    (void)n2;
}
__global__ void k2_kukv(Dev d, const double* q, double* ku, double* kv) {
    COL2(d.nx, d.ny);
    int ip = wrapp(i, d.nx), jp = wrapp(j, d.ny), c2 = IDX2(i, j, d.nx);
    double su = 0.0, sv = 0.0;
    for (int k = 0; k < d.nz; ++k) {
        int c = IDX3(i, j, k, d.nx, d.ny);
        su += d.dz3u[c] * fmin(q[c], q[IDX3(ip, j, k, d.nx, d.ny)]);
        sv += d.dz3v[c] * fmin(q[c], q[IDX3(i, jp, k, d.nx, d.ny)]);
    }
    ku[c2] = su * d.masku[c2]; kv[c2] = sv * d.maskv[c2];
}
__global__ void k_tracer_adv(Dev d, const double* c_, const double* u, const double* v, const double* wf, bool upwind, bool up3, bool lim, double* out) {
    GRID3(d.nx, d.ny, d.nz);
    int ip = wrapp(i, d.nx), im = wrapm(i, d.nx), jp = wrapp(j, d.ny), jm = wrapm(j, d.ny), nz = d.nz;
    auto A = [&](int ii, int jj, int kk) { return IDX3(ii, jj, kk, d.nx, d.ny); };
    int c = A(i, j, k), ce = A(ip, j, k), cw = A(im, j, k), cn = A(i, jp, k), cs = A(i, jm, k);
    double cxe, cxw, cyn, cys;
    auto CV = [&](int kk) { return (kk >= 0 && kk < nz) ? c_[A(i, j, kk)] : 0.0; };
    auto MW = [&](int kk) { return (kk >= 0 && kk < nz) && d.mask3[A(i, j, kk)] > 0.0; };
    if (up3) {
        int ipp = wrapp2(i, d.nx), imm = wrapm2(i, d.nx), jpp = wrapp2(j, d.ny), jmm = wrapm2(j, d.ny);
        cxe = kface(c_[cw], c_[c], c_[ce], c_[A(ipp, j, k)], u[c], d.mask3[cw] > 0.0, d.mask3[A(ipp, j, k)] > 0.0, lim);
        cxw = kface(c_[A(imm, j, k)], c_[cw], c_[c], c_[ce], u[cw], d.mask3[A(imm, j, k)] > 0.0, d.mask3[ce] > 0.0, lim);
        cyn = kface(c_[cs], c_[c], c_[cn], c_[A(i, jpp, k)], v[c], d.mask3[cs] > 0.0, d.mask3[A(i, jpp, k)] > 0.0, lim);
        cys = kface(c_[A(i, jmm, k)], c_[cs], c_[c], c_[cn], v[cs], d.mask3[A(i, jmm, k)] > 0.0, d.mask3[cn] > 0.0, lim);
    } else if (upwind) {
        cxe = u[c] > 0.0 ? c_[c] : c_[ce]; cxw = u[cw] > 0.0 ? c_[cw] : c_[c];
        cyn = v[c] > 0.0 ? c_[c] : c_[cn]; cys = v[cs] > 0.0 ? c_[cs] : c_[c];
    } else {
        cxe = 0.5 * (c_[c] + c_[ce]); cxw = 0.5 * (c_[cw] + c_[c]); cyn = 0.5 * (c_[c] + c_[cn]); cys = 0.5 * (c_[cs] + c_[c]);
    }
    double fxe = d.dz3u[c] * u[c] * cxe, fxw = d.dz3u[cw] * u[cw] * cxw, fyn = d.dz3v[c] * v[c] * cyn, fys = d.dz3v[cs] * v[cs] * cys;
    double hdiv = ((fxe - fxw) / d.dx + (fyn - fys) / d.dy) * d.inv_dz3[c];
    double cft, cfb;
    if (k == 0) cft = c_[c];
    else if (up3) cft = kface(CV(k + 1), c_[c], c_[A(i, j, k - 1)], CV(k - 2), wf[A(i, j, k)], MW(k + 1), MW(k - 2), lim);
    else cft = 0.5 * (c_[A(i, j, k - 1)] + c_[c]);
    if (k == nz - 1) cfb = 0.0;
    else if (up3) cfb = kface(CV(k + 2), c_[A(i, j, k + 1)], c_[c], CV(k - 1), wf[A(i, j, k + 1)], MW(k + 2), MW(k - 1), lim);
    else cfb = 0.5 * (c_[c] + c_[A(i, j, k + 1)]);
    double vdiv = (wf[A(i, j, k)] * cft - wf[A(i, j, k + 1)] * cfb) * d.inv_dz3[c];
    out[c] = (hdiv + vdiv) * d.mask3[c];
}
__global__ void k_tracer_rhs(Dev d, const double* c_, const double* tend, const double* dzb, const double* sflux, double dt, double thv, double* rhs) {
    GRID3(d.nx, d.ny, d.nz);
    int c = IDX3(i, j, k, d.nx, d.ny);
    double r = c_[c] + dt * tend[c] + (1.0 - thv) * dt * dzb[c];
    if (k == 0) r += thv * dt * sflux[IDX2(i, j, d.nx)] * d.inv_dz3[c];
    rhs[c] = r;
}
__global__ void k3_mask(Dev d, double* a) { GRID3(d.nx, d.ny, d.nz); int c = IDX3(i, j, k, d.nx, d.ny); a[c] *= d.mask3[c]; }
__global__ void k3_fill(Dev d, double* a, double v) { GRID3(d.nx, d.ny, d.nz); a[IDX3(i, j, k, d.nx, d.ny)] = v; }
__global__ void k3_axpy(Dev d, double* y, double a, const double* x) { GRID3(d.nx, d.ny, d.nz); int c = IDX3(i, j, k, d.nx, d.ny); y[c] += a * x[c]; }
__global__ void k3_copy(Dev d, const double* s, double* o) { GRID3(d.nx, d.ny, d.nz); int c = IDX3(i, j, k, d.nx, d.ny); o[c] = s[c]; }
__global__ void k3_stress(Dev d, const double* exu, const double* exv, double dt, double thv, double* w3c, double* w3d) {
    GRID3(d.nx, d.ny, d.nz);
    int c = IDX3(i, j, k, d.nx, d.ny);
    double a = dt * exu[c], b = dt * exv[c];
    if (k == 0) { a += thv * dt * d.tau_u[IDX2(i, j, d.nx)] * safe_inv(d.dz3u[c]); b += thv * dt * d.tau_v[IDX2(i, j, d.nx)] * safe_inv(d.dz3v[c]); }
    w3c[c] = a; w3d[c] = b;
}
__global__ void k3_predictor(Dev d, const double* u, const double* v, double dt, double f, double tc, double c1, double thv, bool with_eta,
                             const double* avpv, const double* avpu, const double* vcor, const double* ucor, const double* pgx, const double* pgy,
                             const double* gx2, const double* gy2, const double* dzu, const double* dzv, const double* w3c, const double* w3d,
                             double* gu, double* gv) {
    GRID3(d.nx, d.ny, d.nz);
    int c = IDX3(i, j, k, d.nx, d.ny), c2 = IDX2(i, j, d.nx);
    double a = u[c] + dt * (f * ((1.0 - tc) * avpv[c] + tc * vcor[c]) + pgx[c]) + (1.0 - thv) * dt * dzu[c] + w3c[c];
    double b = v[c] + dt * (-f * ((1.0 - tc) * avpu[c] + tc * ucor[c]) + pgy[c]) + (1.0 - thv) * dt * dzv[c] + w3d[c];
    if (with_eta) { a -= c1 * gx2[c2] * d.mask3u[c]; b -= c1 * gy2[c2] * d.mask3v[c]; }
    gu[c] = a; gv[c] = b;
}
__global__ void k3_backsub(Dev d, const double* ghu, const double* ghv, const double* q, const double* gx2, const double* gy2, double c2, double* uit, double* vit) {
    GRID3(d.nx, d.ny, d.nz);
    int c = IDX3(i, j, k, d.nx, d.ny), c2i = IDX2(i, j, d.nx);
    uit[c] = (ghu[c] - c2 * q[c] * gx2[c2i] * d.mask3u[c]) * d.mask3[c];
    vit[c] = (ghv[c] - c2 * q[c] * gy2[c2i] * d.mask3v[c]) * d.mask3[c];
}
__global__ void k3_split_correct(Dev d, const double* ghu, const double* ghv, const double* umean, const double* vmean, const double* bu, const double* bv, double* uit, double* vit) {
    GRID3(d.nx, d.ny, d.nz);
    int c = IDX3(i, j, k, d.nx, d.ny), c2 = IDX2(i, j, d.nx);
    uit[c] = (ghu[c] - umean[c2] * d.inv_hcu[c2] + bu[c2] * d.inv_hcu[c2]) * d.mask3u[c];  /* face masks (N15) */
    vit[c] = (ghv[c] - vmean[c2] * d.inv_hcv[c2] + bv[c2] * d.inv_hcv[c2]) * d.mask3v[c];
}
__global__ void k3_wcsrc(Dev d, const double* wf, double n2, double* src) {
    GRID3(d.nx, d.ny, d.nz);
    int c = IDX3(i, j, k, d.nx, d.ny);
    src[c] = -n2 * 0.5 * (wf[c] + wf[IDX3(i, j, k + 1, d.nx, d.ny)]);
}
__global__ void k3_eos(Dev d, const double* t, const double* s, int kind, double g_, double rho0, double alpha_t, double beta_s, double t0, double s0, double* b) {
    GRID3(d.nx, d.ny, d.nz);
    int c = IDX3(i, j, k, d.nx, d.ny);
    double rp, z = d.zc[c];
    if (kind == 0) rp = rho0 * (-alpha_t * (t[c] - t0) + beta_s * (s[c] - s0));
    else if (kind == 1) {
        const double a0 = 1.6550e-1, b0 = 7.6554e-1, l1 = 5.9520e-2, l2 = 7.4914e-4, m1 = 1.4970e-4, m2 = 1.1090e-5, nu = 2.4341e-3;
        double ta = t[c] - 10.0, sa = s[c] - 35.0;
